PROGRAM UVTOVOD

USE PARKIND1  ,ONLY : JPIM     ,JPRB
USE GRIB_API
USE MPL_MPIF, ONLY : MPI_COMM_WORLD
USE MPL_MODULE

IMPLICIT NONE

! Should be defined in GRIB_API module
INTEGER, PARAMETER :: GRIB_SECTION_PRODUCT =  1
INTEGER, PARAMETER :: GRIB_SECTION_GRID    =  2
INTEGER, PARAMETER :: GRIB_SECTION_LOCAL   =  4
INTEGER, PARAMETER :: GRIB_SECTION_DATA    =  8
INTEGER, PARAMETER :: GRIB_SECTION_BITMAP  = 16

CHARACTER OPTIONS*20
DATA OPTIONS/'i:o:u:v:d:x:P:h;l;X;'/
CHARACTER*1 OPTLET,CEDITION
CHARACTER*127 ARG,CINGPF,COUTSPF,CPROC,CGRIDTYPE,CSAMPLESFILE

INTEGER(KIND=JPIM) :: ISTACK,GETSTACKUSAGE,OPTVAL
INTEGER(KIND=JPIM) :: NERR,NPROC,NLIN,INGF,NSMAX,NDGL,NV
INTEGER(KIND=JPIM) :: NUCODE,NVCODE,NDCODE,NVOCODE,NLEVS
INTEGER(KIND=JPIM) :: NOUT,NSPEC2,NSPEC2G,NGPTOT,NGPTOTG,IMAXFLD,IPARAM,IOUTSF
INTEGER(KIND=JPIM) :: IMAXU, NBATCHES,IFLD,IFLDU,IFLDV,IFLDD,IFLDVO,NNFLD
INTEGER(KIND=JPIM) :: JROC,IERR,ITAG,IRET,IDX,ISTRUNC
INTEGER(KIND=JPIM) :: JFLD,JGL,JB,IGRIBIN,IGRIBOUT, ISAMPLE
INTEGER(KIND=JPIM) :: GETOPT,MYPROC,JJ,IEDITION
INTEGER(KIND=JPIM) :: IPROC,IPROC_OLD,ICOMM,ICOMM_OLD
INTEGER(KIND=JPIM) ,ALLOCATABLE :: ILEVS(:), NFLD(:), NLOEN(:),ITO(:),NPRCIDS(:)

REAL(KIND=JPRB) :: Z,ZT,TIMEF,ZCODE
REAL(KIND=JPRB),ALLOCATABLE :: ZSPECG(:,:),ZSPEC(:,:),ZFPDAT(:)
REAL(KIND=JPRB),ALLOCATABLE :: ZG(:,:,:),ZGG(:,:)
LOGICAL :: LSCAL,LGRIBEX
!     ------------------------------------------------------------------

#include "setup_trans0.h"
#include "setup_trans.h"
#include "dir_trans.h"
#include "dist_grid.h"
#include "gath_spec.h"
#include "trans_inq.h"

! Initializations
NERR = 0
NOUT = 6
IMAXFLD = 64
IPROC = 1 
LSCAL = .false.
LGRIBEX = .false.

! Set defaults for options

CINGPF   = ' '
COUTSPF = ' '
NLIN=0
NUCODE=131
NVCODE=132
NDCODE=155
NVOCODE=138

! Crack options

DO
  OPTVAL = GETOPT(OPTIONS,ARG)
  IF(OPTVAL <= 0) EXIT
  OPTLET=CHAR(OPTVAL)
  IF(OPTVAL <= 0) EXIT
  IF(OPTLET == 'h') THEN
    CALL USE_UVTOVOD
    STOP
  ELSEIF(OPTLET == 'l') THEN
    NLIN = 1
  ELSEIF(OPTLET == 'i')  THEN
    CINGPF = ARG
  ELSEIF(OPTLET == 'o') THEN
    COUTSPF = ARG
  ELSEIF(OPTLET == 'u') THEN
    NUCODE = ICODE(ARG)
  ELSEIF(OPTLET == 'v') THEN
    NVCODE = ICODE(ARG)
  ELSEIF(OPTLET == 'd') THEN
    NDCODE = ICODE(ARG)
  ELSEIF(OPTLET == 'x') THEN
    NVOCODE = ICODE(ARG)
  ELSEIF(OPTLET == 'P') THEN
    READ(ARG,*) IPROC
  ELSEIF(OPTLET == 'X') THEN
    LGRIBEX = .true.
  ELSE
    CALL USE_UVTOVOD
    CALL ABOR1('UVTOVOD:ERROR IN ARGUMENT')
  ENDIF
ENDDO

IF (IPROC == 1) LSCAL=.true.  !-- serial binary ---

! Message passing setup
! Participating processors limited by -P option 

!--------------------------
 ZT=TIMEF()
 CALL MPL_INIT()

 NPROC=MPL_NPROC()
 MYPROC = MPL_MYRANK()
 IPROC_OLD=NPROC
 IF(IPROC_OLD > IPROC) THEN
   CALL MPL_LOCOMM_CREATE(IPROC,ICOMM) 
   IF(MYPROC > IPROC) THEN
     CALL MPL_BARRIER()
     CALL MPL_END()
     STOP
   ENDIF 
   CALL MPL_SETDFLT_COMM(ICOMM,ICOMM_OLD)
   NPROC=IPROC
 ENDIF
!--------------------------
ALLOCATE(NPRCIDS(NPROC))
DO JJ=1,NPROC
  NPRCIDS(JJ) = JJ
ENDDO
ITAG = 191919

IF (LGRIBEX) CALL GRIB_GRIBEX_MODE_ON()

IF(MYPROC == 1) THEN
  IF(CINGPF == ' ') THEN
    PRINT *,' INPUT G-P FILE NAME HAS NOT BEEN SUPPLIED'
    PRINT *,' FILE fort.11 WILL BE USED AS INPUT'
    CINGPF = 'fort.11'
  ENDIF
  IF(COUTSPF == ' ') THEN
    PRINT *,' OUTPUT SPECTRAL FILE NAME HAS NOT BEEN SUPPLIED'
    PRINT *,' FILE fort.12 WILL BE USED FOR SPECTRAL OUTPUT'
    COUTSPF = 'fort.12'
  ENDIF
  PRINT *,' CODE FOR U-WIND=',NUCODE
  PRINT *,' CODE FOR V-WIND=',NVCODE
  PRINT *,' CODE FOR DIVERGENCE=',NDCODE
  PRINT *,' CODE FOR VORTICITY=',NVOCODE
  PRINT *,' GRIBEX compability mode=',LGRIBEX
ENDIF

! Find spectral resolution

CALL GRIB_OPEN_FILE(INGF,CINGPF,'R',IRET)
IF(IRET /= GRIB_SUCCESS) THEN
  WRITE(NERR,*) ' ERROR OPENING FILE INPUT GRIDPOINT FILE',CINGPF,IRET
  CALL ABOR1('UVTOVOD: ERROR OPENING FILE INPUT GRIDPOINT FILE')
ENDIF

! Set up spectral transform (all processors) and determine offsets (MYPROC==1)

DO
  CALL GRIB_NEW_FROM_FILE(INGF,IGRIBIN,IRET)
  IF(IRET /= GRIB_SUCCESS) THEN
    WRITE(NERR,*)' ERROR IN FILE ',CINGPF,' : GRIB_NEW_FROM_FILE RETURNS ',IRET
    CALL ABOR1('UVTOVOD: GRIB_NEW_FROM_FILE ERROR')
  ENDIF
  CALL GRIB_GET(IGRIBIN,'paramId',IPARAM)
  IF(IPARAM == NUCODE .OR. IPARAM /= NVCODE ) THEN
    EXIT
  ENDIF
  CALL GRIB_RELEASE(IGRIBIN)
ENDDO

CALL GRIB_GET(IGRIBIN,'edition',IEDITION)
CALL GRIB_GET(IGRIBIN,'gridType',CGRIDTYPE)
IF(TRIM(CGRIDTYPE) /= 'regular_gg' .AND. TRIM(CGRIDTYPE) /= 'reduced_gg' ) THEN
  WRITE(NERR,*)' INPUT DATA NOT IN GAUSSIAN GRID'
  CALL ABOR1('UVTOVOD: INPUT DATA NOT IN GAUSSIAN GRID')
ENDIF

!Decide spectral resolution

CALL GRIB_GET(IGRIBIN,'Nj',NDGL)
CALL GRIB_GET(IGRIBIN,'NV',NV)
ALLOCATE(NLOEN(NDGL))
IF(TRIM(CGRIDTYPE) == 'reduced_gg') THEN
  CALL GRIB_GET(IGRIBIN,'pl',NLOEN)
ELSE
  CALL GRIB_GET(IGRIBIN,'Ni',NLOEN(1))    
  DO JGL=2,NDGL
    NLOEN(JGL) = NLOEN(1)
  ENDDO
ENDIF

IF(NLIN == 0) THEN
  NSMAX=(2*NDGL-1)/3
ELSE
  NSMAX=(2*NDGL-1)/2
ENDIF
IF(NSMAX > 511) IMAXFLD=8
IF(NSMAX > 800) IMAXFLD=2
IMAXU = IMAXFLD/2

! Prepare for transforms

CALL SETUP_TRANS0(KOUT=NOUT,KERR=0,KPRINTLEV=0,KMAX_RESOL=1,&
  &KPRGPNS=NPROC,KPRGPEW=1,KPRTRW=NPROC,LDMPOFF=LSCAL)
CALL SETUP_TRANS(KSMAX=NSMAX,KDGL=NDGL,KLOEN=NLOEN,LDSPLIT=.FALSE.)

CALL TRANS_INQ(KSPEC2=NSPEC2,KSPEC2G=NSPEC2G,KGPTOT=NGPTOT,KGPTOTG=NGPTOTG)

ALLOCATE(ZSPECG(IMAXFLD,NSPEC2G))
ALLOCATE(ZSPEC(IMAXFLD,NSPEC2))
ALLOCATE(ZFPDAT(MAX(NGPTOTG,NSPEC2G)))
ALLOCATE(ZG(NGPTOT,IMAXFLD,1))
ALLOCATE(ZGG(NGPTOTG,IMAXFLD))
ALLOCATE(ITO(IMAXFLD))

! Open files

IF(MYPROC == 1) THEN
  CALL GRIB_INDEX_CREATE(IDX,CINGPF,'paramId,level',IRET)
  IF(IRET /= GRIB_SUCCESS) THEN
    WRITE(NERR,*) ' ERROR OPENING FILE INPUT GRIDPOINT FILE',CINGPF,IRET
    CALL ABOR1('UVTOVOD: ERROR OPENING INPUT GRIDPOINT FILE')
  ENDIF

! Check on contents of input file

  CALL GRIB_INDEX_GET_SIZE(IDX,'level',NLEVS)
  ALLOCATE(ILEVS(NLEVS))
  CALL GRIB_INDEX_GET(IDX,'level',ILEVS)

  NBATCHES=NLEVS/IMAXU+1
  ALLOCATE(NFLD(NBATCHES))
  DO JB=1,NBATCHES-1
    NFLD(JB)=IMAXU
  ENDDO
  NFLD(NBATCHES)=MOD(NLEVS,IMAXU)
  IF(NFLD(NBATCHES) == 0) NBATCHES=NBATCHES-1
  IF(NPROC > 1) THEN
    DO JROC=2,NPROC
      CALL MPL_SEND(NBATCHES,KDEST=NPRCIDS(JROC),KTAG=ITAG)
    ENDDO
  ENDIF
  WRITE(NOUT,*) ' UVTOVOD, ',NLEVS,' FIELDS OF U and V IN ',NBATCHES,' BATCHES'

! Set up output file

  CALL GRIB_OPEN_FILE(IOUTSF,COUTSPF,'W',IRET)
  IF(IRET /= GRIB_SUCCESS) THEN
    WRITE(NERR,*) ' ERROR OPENING FILE OUTPUT SPECTRAL FILE',COUTSPF,IRET
    CALL ABOR1('UVTOVOD: ERROR OPENING OUTPUT SPECTRAL FILE')
  ENDIF

  WRITE(CEDITION,'(I1)') IEDITION
  CSAMPLESFILE = 'sh_ml_grib'//CEDITION
  CALL GRIB_NEW_FROM_SAMPLES(ISAMPLE,CSAMPLESFILE,IRET)
  IF(IRET /= GRIB_SUCCESS) THEN
    WRITE(NERR,*)' ERROR GRIB_NEW_FROM_SAMPLES ',CSAMPLESFILE
    CALL ABOR1('UVTOVOD: ERROR GRIB_NEW_FROM_SAMPLES')
  ENDIF

  CALL GRIB_UTIL_SECTIONS_COPY(IGRIBIN,ISAMPLE, &
    & GRIB_SECTION_PRODUCT+GRIB_SECTION_LOCAL,IGRIBOUT,IRET)
  IF(IRET /= GRIB_SUCCESS) THEN
    WRITE(NERR,*)' ERROR GRIB_UTIL_SECTIONS_COPY ',IRET
    CALL ABOR1('UVTOVOD: ERROR GRIB_UTIL_SECTIONS_COPY')
  ENDIF
    
  CALL GRIB_SET(IGRIBOUT,'J',NSMAX)
  CALL GRIB_SET(IGRIBOUT,'K',NSMAX)
  CALL GRIB_SET(IGRIBOUT,'M',NSMAX)
  
  IF (NSMAX >= 213) THEN
    ISTRUNC = 20
  ELSE
    ISTRUNC = MIN(10,NSMAX)
  ENDIF
  CALL GRIB_SET(IGRIBOUT,'JS',ISTRUNC)
  CALL GRIB_SET(IGRIBOUT,'KS',ISTRUNC)
  CALL GRIB_SET(IGRIBOUT,'MS',ISTRUNC)

  CALL GRIB_SET(IGRIBOUT,'NV',NV)
  
  IF (LGRIBEX) THEN
    CALL GRIB_SET(IGRIBOUT,'computeLaplacianOperator', 0)
    CALL GRIB_SET(IGRIBOUT,'laplacianOperator',0.5_JPRB)
  ENDIF
ELSE
  CALL MPL_RECV(NBATCHES,KSOURCE=NPRCIDS(1),KTAG=ITAG)
ENDIF

CALL GRIB_RELEASE(IGRIBIN)
CALL GRIB_CLOSE_FILE(INGF,IRET)

! Syncronize processors
IF(NPROC > 1) THEN
  CALL MPL_BARRIER()
ENDIF

! Gridpoint to spectral transform

ITO(:) = 1
IFLDU=0
IFLDV=0
IFLDD=0
IFLDVO=0
DO JB=1,NBATCHES
  IF(MYPROC == 1) THEN
    WRITE(NOUT,*) ' WORKING ON BATCH No ',JB,' (',NFLD(JB),' FIELDS)'
    IFLD=2*NFLD(JB)
    ! Read and decode gridpoint field
    DO JFLD=1,NFLD(JB)
      IFLDU=IFLDU+1
      CALL GRIB_INDEX_SELECT(IDX,'paramId',NUCODE)
      CALL GRIB_INDEX_SELECT(IDX,'level',ILEVS(IFLDU))
      CALL GRIB_NEW_FROM_INDEX(IDX,IGRIBIN,IRET)
      IF(IRET /= GRIB_SUCCESS) THEN
        WRITE(NERR,*) ' GRIB_NEW_FROM_INDEX U LEVEL=',ILEVS(IFLDU),' IRET=',IRET        
        CALL ABOR1('  GRIB_NEW_FROM_INDEX FAILED')
      ENDIF
      CALL GRIB_GET(IGRIBIN,'values',ZGG(:,JFLD))
      IF(IRET /= GRIB_SUCCESS) THEN
        WRITE(NERR,*) ' GRIB_GET values U LEVEL=',ILEVS(IFLDU),' IRET=',IRET        
        CALL ABOR1('  GRIB_GET values FAILED')
      ENDIF
      CALL GRIB_RELEASE(IGRIBIN)
    ENDDO
    DO JFLD=1,NFLD(JB)
      IFLDV=IFLDV+1
      CALL GRIB_INDEX_SELECT(IDX,'paramId',NVCODE)
      CALL GRIB_INDEX_SELECT(IDX,'level',ILEVS(IFLDV))
      CALL GRIB_NEW_FROM_INDEX(IDX,IGRIBIN,IRET)
      IF(IRET /= GRIB_SUCCESS) THEN
        WRITE(NERR,*) ' GRIB_NEW_FROM_INDEX V LEVEL=',ILEVS(IFLDV),' IRET=',IRET        
        CALL ABOR1('  GRIB_NEW_FROM_INDEX FAILED')
      ENDIF
      CALL GRIB_GET(IGRIBIN,'values',ZGG(:,JFLD+NFLD(JB)))
      IF(IRET /= GRIB_SUCCESS) THEN
        WRITE(NERR,*) ' GRIB_GET values V LEVEL=',ILEVS(IFLDV),' IRET=',IRET        
        CALL ABOR1('  GRIB_GET values FAILED')
      ENDIF
      CALL GRIB_RELEASE(IGRIBIN)
    ENDDO

    ! Send number of fields in this batch to other processors
    IF(NPROC > 1) THEN
      DO JROC=2,NPROC
        CALL MPL_SEND(IFLD,KDEST=NPRCIDS(JROC),KTAG=ITAG)
      ENDDO
    ENDIF
  ELSE
    ! Receive number of fields in this batch
    CALL MPL_RECV(IFLD,KSOURCE=NPRCIDS(1),KTAG=ITAG)
  ENDIF
  ! Syncronize processors
  IF(NPROC > 1) THEN
    CALL MPL_BARRIER()
  ENDIF
  NNFLD=IFLD/2
  ! Distribute gridpoint fields to processors
  CALL DIST_GRID(PGPG=ZGG,KFDISTG=IFLD,KFROM=ITO,PGP=ZG)
  ! Spectral transform
  CALL DIR_TRANS(PSPVOR=ZSPEC(1:NNFLD,:),PSPDIV=ZSPEC(NNFLD+1:IFLD,:),PGP=ZG)
  ! Gather spectral fields to processor 1
  CALL GATH_SPEC(PSPECG=ZSPECG,KFGATHG=IFLD,KTO=ITO,PSPEC=ZSPEC)

  ! Code and write out spectral fields

  IF(MYPROC == 1) THEN
    DO JJ=1,2
      DO JFLD=1,NFLD(JB)
        IF(JJ == 1) THEN
          IFLDVO = IFLDVO + 1
          CALL GRIB_SET(IGRIBOUT,'paramId',NVOCODE)
          CALL GRIB_SET(IGRIBOUT,'level',ILEVS(IFLDVO))
        ELSE
          IFLDD = IFLDD + 1
          CALL GRIB_SET(IGRIBOUT,'paramId',NDCODE)
          CALL GRIB_SET(IGRIBOUT,'level',ILEVS(IFLDD))
        ENDIF
        ZFPDAT(1:NSPEC2G) = ZSPECG(JFLD+(JJ-1)*NFLD(JB),:)
        CALL GRIB_SET(IGRIBOUT,'values',ZFPDAT(1:NSPEC2G))
        CALL GRIB_WRITE(IGRIBOUT,IOUTSF,IRET)
        IF(IRET /= GRIB_SUCCESS) THEN
          WRITE(NERR,*)'UVTOVOD: ERROR GRIB_WRITE ', IRET
          CALL ABOR1('UVTOVOD: ERROR GRIB_WRITE')
        ENDIF
      ENDDO
    ENDDO
  ENDIF

  ! Syncronize processors
  IF(NPROC > 1) THEN
    CALL MPL_BARRIER()
  ENDIF
ENDDO

IF(MYPROC == 1) THEN
  CALL GRIB_RELEASE(IGRIBOUT)
  CALL GRIB_INDEX_RELEASE(IDX)
  CALL GRIB_CLOSE_FILE(IOUTSF)
ENDIF

!           gather stack usage statistics
ISTACK = GETSTACKUSAGE()
IF(MYPROC == 1) THEN
  WRITE(NOUT,9000) istack

9000 FORMAT("Stack Utilisation Information",/,&
          &"=============================",//,&
          &"Node           Size(Bytes)",/,&
          &"====           ===========",//,&
          &"   1",11x,I10)

  DO JROC=2,NPROC
    CALL MPL_RECV(ISTACK,KSOURCE=NPRCIDS(JROC),KTAG=JROC, &
         & CDSTRING='UVTOVOD:')
    WRITE(NOUT,'(I4,11X,I10)') JROC,ISTACK
  ENDDO
ELSE
  CALL MPL_SEND(ISTACK,KDEST=NPRCIDS(1),KTAG=MYPROC, &
       &   CDSTRING='UVTOVOD:')
ENDIF

!Close down message passing
!--------------------------
 IF(IPROC_OLD > IPROC) THEN
   MPL_COMM_OML(1)=MPI_COMM_WORLD
   MPL_NUMPROC=IPROC_OLD
   CALL MPL_SETDFLT_COMM(ICOMM_OLD,ICOMM)
 ENDIF

 CALL MPL_BARRIER()
 CALL MPL_END()
 ZT=(TIMEF()-ZT)/1000.0_JPRB
 IF(MYPROC == 1) write(0,'(a,I3,a,I4,a,F9.2,a)') &
    & "UVTOVOD, on",NPROC," out of",IPROC_OLD," procs, took",ZT," sec"
!--------------------------

CONTAINS  

!     ------------------------------------------------------------------

SUBROUTINE USE_UVTOVOD

!   WRITE MESSAGE TO INFORM ABOUT CORRECT USE OF PROGRAM

WRITE(NOUT,*) ' CORRECT OPTIONS AND ARGUMENTS FOR UVTOVOD ARE :'
WRITE(NOUT,*) '   -i      input filename (grid-point) (def: fort.11)'
WRITE(NOUT,*) '   -o      output spectral  filename (def: fort.12)'
WRITE(NOUT,*) '   -l      if linear grid (default quadratic)'
WRITE(NOUT,*) '   -P      number of processors to use (default 1)'
WRITE(NOUT,*) '   -u      code for x-component of input field (def:131)'
WRITE(NOUT,*) '   -v      code for y-component of input field (def:132)'
WRITE(NOUT,*) '   -d      code for divergence output field (def:155)'
WRITE(NOUT,*) '   -x      code for vorticity output field (def:138)'
WRITE(NERR,*) '   -X      try make output identical to old GRIBEX'
WRITE(NOUT,*) '   -h      displays options and arguments'

END SUBROUTINE USE_UVTOVOD

!     ------------------------------------------------------------------

FUNCTION ICODE(CFIELD)
  IMPLICIT NONE
  
  INTEGER(KIND=JPIM) :: ICODE
  CHARACTER(LEN=*), INTENT(IN) :: CFIELD

  REAL(KIND=JPRB) :: ZCODE
  INTEGER(KIND=JPIM) :: ITABLE

  READ(CFIELD,'(F7.0)') ZCODE

  ! Handle possible param.table notation
  ICODE = FLOOR(ZCODE)
  ITABLE = NINT(1000*(ZCODE-ICODE))
  IF (ITABLE /= 128) ICODE = 1000*ITABLE + ICODE

END FUNCTION ICODE

!     ------------------------------------------------------------------

END PROGRAM UVTOVOD

