PROGRAM GRIB_SET_VTABLE

! Nils Wedi, setting grib_headers for fullpos output resolutions

USE GRIB_API

IMPLICIT NONE

INTEGER, PARAMETER :: JPIM = SELECTED_INT_KIND(9)
INTEGER, PARAMETER :: JPRB = SELECTED_REAL_KIND(13,300)

INTEGER(KIND=JPIM) ::   OPTVAL
INTEGER(KIND=JPIM) :: GETOPT
CHARACTER OPTIONS*16
DATA OPTIONS/'i:r:l:n:S:G:U:h;'/
CHARACTER ARG*128
CHARACTER OPTLET
CHARACTER*128 CINF
CHARACTER*128 COUTFGG
CHARACTER*128 COUTFGGUA
CHARACTER*128 COUTFSP
CHARACTER(LEN=512) :: ERROR_MSG

!     LOCAL INTEGER SCALARS
INTEGER(KIND=JPIM) :: NSMAX, NFLEV, NLAT, NLATO, NLOCDEF
INTEGER(KIND=JPIM) :: IFILE, IGRIB, IGRIBI, IPLPresent, INFILE
INTEGER(KIND=JPIM) :: ICOUNT, I, IERR, IRET, ITOTAL1, IDGL, ITOTAL0, J
REAL(KIND=JPRB) :: ZLAT0, ZLAT1, ZLON0, ZLON1

! max resol T10000
INTEGER(KIND=JPIM) :: NLOENG(20000), NRGRI(20000)
INTEGER(KIND=JPIM),ALLOCATABLE :: NLOENI(:)
! max vert 400
REAL(KIND=JPRB) :: DVALH(0:400), DVBH(0:400)
REAL(KIND=JPRB) :: ZPV(0:400)


LOGICAL :: LLREDGR

NAMELIST /NAMVV1/ DVALH, DVBH
NAMELIST /NAMRGRI/ NRGRI

CINF=' '
COUTFSP=' '
COUTFGG=' '
COUTFGGUA=' '
LLREDGR=.TRUE.
NLAT=0

DO
  OPTVAL=GETOPT(OPTIONS,ARG)
  IF(OPTVAL <= 0) EXIT
  OPTLET=CHAR(OPTVAL)
  IF(OPTVAL <= 0) EXIT
  IF(OPTLET == 'h') THEN
    PRINT *,&
        'grib_set_vtable -i sfc_gg -r latitudes -l levels -n NSMAX -S sp_out -G gg_out -U ggua_out (vtable/rtable read from fort.4)'
    STOP
  ELSEIF(OPTLET == 'r')  THEN
    LLREDGR=.FALSE.
    READ(ARG,*) NLAT
  ELSEIF(OPTLET == 'i')  THEN
    CINF=ARG
  ELSEIF(OPTLET == 'n')  THEN
    READ(ARG,*) NSMAX
  ELSEIF(OPTLET == 'l')  THEN
    READ(ARG,*) NFLEV
  ELSEIF(OPTLET == 'S')  THEN
    COUTFSP=ARG
  ELSEIF(OPTLET == 'G')  THEN
    COUTFGG=ARG
  ENDIF
ENDDO
IF(CINF == ' ') THEN
  PRINT *,' INPUT FILE NAME HAS NOT BEEN SUPPLIED'
  STOP
ENDIF
IF(COUTFSP == ' ') THEN
  PRINT *,' OUTPUT FILE NAME HAS NOT BEEN SUPPLIED'
  PRINT *,' FILE fort.11 WILL BE USED AS INPUT'
  COUTFSP='fort.11'
ENDIF
IF(COUTFGG == ' ') THEN
  PRINT *,' OUTPUT FILE NAME HAS NOT BEEN SUPPLIED'
  PRINT *,' FILE fort.12 WILL BE USED AS INPUT'
  COUTFGG='fort.12'
ENDIF
IF(COUTFGGUA == ' ') THEN
  IF(COUTFGG /= ' ') THEN
    COUTFGGUA='UA'//COUTFGG
  ELSE
    PRINT *,' OUTPUT FILE NAME HAS NOT BEEN SUPPLIED'
    PRINT *,' FILE fort.13 WILL BE USED AS INPUT'
    COUTFGGUA='fort.13'
  ENDIF
ENDIF

! +++++++++++++++++++++++ spectral grib-header ++++++++++++++++++++++++

CALL GRIB_OPEN_FILE(INFILE,CINF,'R')
CALL GRIB_NEW_FROM_FILE(INFILE,IGRIBI,IRET)

IF (IRET /= 0 ) THEN
  CALL GRIB_GET_ERROR_STRING(IRET,ERROR_MSG)
  WRITE(*,'(2A)')' GRIB_API ERROR: ',ERROR_MSG
ENDIF

CALL GRIB_GET(IGRIBI,'numberOfPointsAlongAMeridian',NLATO)
CALL GRIB_GET(IGRIBI,'latitudeOfFirstGridPointInDegrees',ZLAT0)
CALL GRIB_GET(IGRIBI,'longitudeOfFirstGridPointInDegrees',ZLON0)
CALL GRIB_GET(IGRIBI,'latitudeOfLastGridPointInDegrees',ZLAT1)
CALL GRIB_GET(IGRIBI,'longitudeOfLastGridPointInDegrees',ZLON1)
CALL GRIB_GET(IGRIBI,'PLPresent',IPLPresent)
CALL GRIB_GET(IGRIBI,'localDefinitionNumber',NLOCDEF)
IF( .NOT.ALLOCATED(NLOENI)) ALLOCATE(NLOENI(3*NLATO))
IF (IPLPresent == 0) THEN
  WRITE(0,*) ' Full grid, no need to check any further '
ELSE
  CALL GRIB_GET(IGRIBI,'pl',NLOENI)
ENDIF

!CALL GRIB_RELEASE(IGRIBI)
CALL GRIB_CLOSE_FILE(INFILE)

! +++++++++++++++++++++++ spectral grib-header ++++++++++++++++++++++++

NRGRI(:)=0

! read vtable file from fort.4
READ(4,NAMVV1)
! read rtable file from fort.4
READ(4,NAMRGRI)

CALL GRIB_NEW_FROM_SAMPLES(IGRIB,'sh_ml',STATUS=IRET)
IF (IRET /= 0 ) THEN
  CALL GRIB_GET_ERROR_STRING(IRET,ERROR_MSG)
  WRITE(*,'(2A)')' GRIB_API ERROR: ',ERROR_MSG
ENDIF

WRITE(0,*) 'NFLEV=',NFLEV,' NSMAX=',NSMAX 
CALL GRIB_SET(IGRIB,'pentagonalResolutionParameterJ',NSMAX,IERR)
CALL GRIB_SET(IGRIB,'pentagonalResolutionParameterK',NSMAX,IERR)
CALL GRIB_SET(IGRIB,'pentagonalResolutionParameterM',NSMAX,IERR)
CALL GRIB_SET(IGRIB,'numberOfVerticalCoordinateValues',NFLEV,IERR)

! set vtable from file
ZPV(:)=0.0_JPRB
ICOUNT=0
DO I=0,NFLEV
  ZPV(ICOUNT)=DVALH(I)
  ICOUNT=ICOUNT+1
ENDDO
DO I=0,NFLEV
  ZPV(ICOUNT)=DVBH(I)
  ICOUNT=ICOUNT+1
ENDDO
CALL GRIB_SET(IGRIB,'pv',ZPV(0:ICOUNT-1),IERR)

! write out new output grib-header sh_ml
CALL GRIB_OPEN_FILE(IFILE,COUTFSP,'W')
CALL GRIB_WRITE(IGRIB,IFILE)
CALL GRIB_RELEASE(IGRIB)
CALL GRIB_CLOSE_FILE(IFILE)

! +++++++++++++++++++++++ gridpoint sfc grib-header ++++++++++++++++++++++++

! write out new output grib-header gg_sfc
!CALL GRIB_NEW_FROM_SAMPLES(IGRIB,'gg_sfc',STATUS=IRET)
!IF (IRET /= 0 ) THEN
!  CALL GRIB_GET_ERROR_STRING(IRET,ERROR_MSG)
!  WRITE(*,'(2A)')' GRIB_API ERROR: ',ERROR_MSG
!ENDIF

IF( LLREDGR ) THEN
  IDGL=1
  ITOTAL1=0
  DO WHILE( NRGRI(IDGL)>0 )
    ITOTAL1 = ITOTAL1 + NRGRI(IDGL)
    IDGL=IDGL+1
  ENDDO
  IDGL=IDGL-1
  WRITE(0,*) ' Reduced grid .... '
  ITOTAL0=0
  DO J=1,NLATO
    ITOTAL0=ITOTAL0+NLOENI(J)
  ENDDO

  WRITE(0,*) 'TOTAL POINTS= ',ITOTAL1,' LATITUDES= ',IDGL, 'TOTAL POINTS INPUT= ',ITOTAL0
  IF( ITOTAL1 /= ITOTAL0 ) THEN
    WRITE(0,*) 'WARNING, INCONSISTENT NUMBER OF POINTS'
    STOP
  ENDIF
  
  CALL GRIB_SET(IGRIBI,'numberOfPointsAlongAMeridian',IDGL)
  CALL GRIB_SET(IGRIBI,'PLPresent',1)
  CALL GRIB_SET(IGRIBI,'pl',NRGRI(1:IDGL))
  CALL GRIB_SET(IGRIBI,'N',IDGL/2)
ELSE
  WRITE(0,*) ' Regular grid, .... '
  CALL GRIB_SET(IGRIBI,'numberOfPointsAlongAMeridian',NLAT)
  CALL GRIB_SET(IGRIBI,'numberOfPointsAlongAParallel',2*NLAT)
  CALL GRIB_SET(IGRIBI,'PLPresent',0)
ENDIF

CALL GRIB_OPEN_FILE(IFILE,COUTFGG,'W')
CALL GRIB_WRITE(IGRIBI,IFILE)
CALL GRIB_RELEASE(IGRIBI)
CALL GRIB_CLOSE_FILE(IFILE)

! +++++++++++++++++++++++ gridpoint gg ua grib-header ++++++++++++++++++++++++

! write out new output grib-header reduced_gg_ml_grib2
CALL GRIB_NEW_FROM_SAMPLES(IGRIB,'reduced_gg_ml_grib2',STATUS=IRET)
IF (IRET /= 0 ) THEN
  CALL GRIB_GET_ERROR_STRING(IRET,ERROR_MSG)
  WRITE(*,'(2A)')' GRIB_API ERROR: ',ERROR_MSG
ENDIF

IF( LLREDGR ) THEN
  IDGL=1
  ITOTAL1=0
  DO WHILE( NRGRI(IDGL)>0 )
    ITOTAL1 = ITOTAL1 + NRGRI(IDGL)
    IDGL=IDGL+1
  ENDDO
  IDGL=IDGL-1
!  WRITE(0,*) ' Reduced grid .... '
!  WRITE(0,*) 'TOTAL POINTS= ',ITOTAL1,' LATITUDES= ',IDGL

  CALL GRIB_SET(IGRIB,'numberOfPointsAlongAMeridian',IDGL)
  CALL GRIB_SET(IGRIB,'PLPresent',1)
  CALL GRIB_SET(IGRIB,'pl',NRGRI(1:IDGL))
  CALL GRIB_SET(IGRIB,'N',IDGL/2)
ELSE
  WRITE(0,*) ' Regular grid, .... '
  CALL GRIB_SET(IGRIB,'numberOfPointsAlongAMeridian',NLAT)
  CALL GRIB_SET(IGRIB,'numberOfPointsAlongAParallel',2*NLAT)
  CALL GRIB_SET(IGRIB,'PLPresent',0)
ENDIF

CALL GRIB_SET(IGRIB,'latitudeOfFirstGridPointInDegrees',ZLAT0)
CALL GRIB_SET(IGRIB,'longitudeOfFirstGridPointInDegrees',ZLON0)
CALL GRIB_SET(IGRIB,'latitudeOfLastGridPointInDegrees',ZLAT1)
CALL GRIB_SET(IGRIB,'longitudeOfLastGridPointInDegrees',ZLON1)
CALL GRIB_SET(IGRIB,'setLocalDefinition',1)
IF( NLOCDEF /=0 ) CALL GRIB_SET(IGRIB,'localDefinitionNumber',NLOCDEF)
CALL GRIB_SET(IGRIB,'pv',ZPV(0:ICOUNT-1),IERR)

CALL GRIB_OPEN_FILE(IFILE,COUTFGGUA,'W')
CALL GRIB_WRITE(IGRIB,IFILE)
CALL GRIB_RELEASE(IGRIB)
CALL GRIB_CLOSE_FILE(IFILE)

END PROGRAM GRIB_SET_VTABLE
