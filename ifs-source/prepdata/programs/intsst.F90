PROGRAM INTSST
!
!       ORIGINAL  *P. VITERBO*     ECMWF    7-4-94
!                  N. WEDI         ECMWF    1996 UPDATE FUJITSU
!                  P. VITERBO      ECMWF    30-10-1997 ADD MONTHLY ALBEDO
!                  P. VITERBO      ECMWF    28-08-1998 ADD ALBEDO HANDLING
!                                                      FOR SEASONAL FORECASTS
!                  P. VITERBO      ECMWF     5-07-1999 ADD SEA-ICE FRACTION
!                  P. VITERBO      ECMWF     22-03-2000 ADD OPTIONS -A AND -O
!                  M. HORTAL       ECMWF     18-09-2001 FREE FORMAT FORTRAN
!                  JJMorcrette     ECMWF    20060915   MODIS ALBEDO
!                  S.Boussetta/G.Balsamo ECMWF 20090611 Monthly LAI
!                  T. Wilhelmsson  ECMWF    2009-12-02 REPLACE GRIBEX WITH GRIB_API
!                  T. Wilhelmsson  ECMWF    2014-11-12 ALLOCATION, VECTORIZATION AND OPENMP
!                  R. Hogan        ECMWF    2019-02-15 6-component MODIS albedo
!
!    THIS PROGRAM INTERPOLATES SOIL TEMPERATURES FROM ONE RESOLUTION
!    TO ANOTHER, IF NEEDED, IT ALSO PUTS THE ALBEDO IN THE INTERPOLATED
!    FILE. IF NEEDED IT ALSO CREATES INFORMATION ON THE SEA-ICE FRACTION
!    EITHER BY INTERPOLATING THE INPUT FIELD OR BY CREATING THAT FROM
!    SST. ALTERNATIVELY, IN THE CASE OF A SEASONAL FORECAST, IT CREATES
!    A CONSECUTIVE SET OF MONTHLY ALBEDOS THAT SPANS THE INTEGRATION
!    PERIOD. YET ANOTHER MODE (-A) IS TO INTERSPERSE THE TIME-INTERPOLATED
!    MONTHLY ALBEDO WITH THE SST INFORMATION (NO SPATIAL INTERPOLATION),
!    AN OPTION FOR PRE-PREPARED SSTS AT THE RIGHT RESOLUTION, SUCH AS
!    AMIP. LASTLY, IF THERE IS ONLY ONE EVENT OF Z/LSM IN THE INPUT FILE
!    CALL THE ABSOLUTE WITH -O. INPUTS AND OUTPUTS ARE GRIB CODED.
!
USE PARKIND1,ONLY : JPIM, JPRB
USE GRIB_API

IMPLICIT NONE

! Should be defined in GRIB_API module
INTEGER, PARAMETER :: GRIB_SECTION_PRODUCT =  1
INTEGER, PARAMETER :: GRIB_SECTION_GRID    =  2
INTEGER, PARAMETER :: GRIB_SECTION_LOCAL   =  4
INTEGER, PARAMETER :: GRIB_SECTION_DATA    =  8
INTEGER, PARAMETER :: GRIB_SECTION_BITMAP  = 16

INTEGER(KIND=JPIM), PARAMETER :: JMON=12, JPCLIM=13

INTEGER(KIND=JPIM) ::  GETOPT
INTEGER(KIND=JPIM) :: OPTVAL
CHARACTER OPTLET, ARG*127, OPTIONS*21
DATA OPTIONS/'s:g:z:o:a:D:E:S:i:AO?'/
CHARACTER*128 YINPF1, YINPF2, YINPF3, YINPF4, YOUTF,YINICE
!
INTEGER(KIND=JPIM), ALLOCATABLE :: ILNO(:), ILNI(:)
REAL(KIND=JPRB), ALLOCATABLE :: ZLTO(:), ZLTI(:)
REAL(KIND=JPRB), ALLOCATABLE :: XI(:), SLMI(:,:), STI(:,:), ZI(:,:), CI(:,:), ZIZERO(:,:)
REAL(KIND=JPRB), ALLOCATABLE :: XO(:), SLMO(:,:), STO(:,:), ZO(:,:), CO(:,:), ZOZERO(:,:), XCO(:)
REAL(KIND=JPRB), ALLOCATABLE :: CLIM(:,:,:),EXPT(:),ZSEC4(:)
LOGICAL LLMAL,LLFIRST,LLSEAS,LLAMIPSST,LLONEZSST,LLREADZSST
INTEGER(KIND=JPIM) :: KGRDAT, KSEC, KAAAA, KMM, KDD, KSS, IARG,  IDATE, ISTEP, IGRBC
INTEGER(KIND=JPIM) :: ICODEMO(JPCLIM+2),ICLIMCOD(12,JPCLIM+2)
INTEGER(KIND=JPIM) :: INZLSMF, INSSTF, INSFCF, INMALF, IOUTF
INTEGER(KIND=JPIM) :: INZLSM,  INSST,  INSFC,  INSFC1, INMAL,  IOUT, IOUT1
INTEGER(KIND=JPIM) :: ICLAN, JFI, ILTRUE, IWORD, IPAR, IGGO, IGLO, IGLONO, J, JG ,ILAKE ,L
INTEGER(KIND=JPIM) :: LEN, LENF, IFOUNDFI, ICODE, IMO, IMM, IMB, IYB, IYY, IY, IGGI, IGLI, IGLA, IGLONI
INTEGER(KIND=JPIM) :: JCAN, JL, IHH, ISS, IDD, IMT1, IMT2, IYT1, IYT2, IRET,KUNIT1
INTEGER(KIND=JPIM) :: IPLP, INTIME, INDATE, ISDATE, ISTIME
REAL(KIND=JPRB)    :: ZPI, ZLATO, ZLATI, ZJDB, ZJDE, ZJD, RTT, RTUPPER, RTFREEZ
REAL(KIND=JPRB)    :: ZT1, ZT2, ZT, ZWEI1, ZWEI2

!  FUNCTIONS
INTEGER(KIND=JPIM) ::  NYYYY, NMM, NDD, NZZAA, NZZMM, ICLMON
REAL(KIND=JPRB)    ::  RJUDAT, RTIME, RDAY

DATA LLFIRST/.TRUE./

!     ------------------------------------------------------------------
!
! - TIME FUNCTIONS
!   THE DESCRIPTIONS ARE IN THE ANNEX 1 OF THE DOCUMENTATION
!
! TIME
!
! NDD   : EXTRAXT DD FROM YYYYMMDD
! NMM   : EXTRACT MM FROM YYYYMMDD
! NYYYY : EXTRACT YYYY FROM YYYYMMDD
! RTIME : RETURNS THE TIME OF THE MODEL (IN SECONDS OF COURSE!)
!
NDD(KGRDAT)  =MOD(KGRDAT,100)
NMM(KGRDAT)  =MOD((KGRDAT-NDD(KGRDAT))/100,100)
NYYYY(KGRDAT)=KGRDAT/10000
!
NZZAA(KAAAA,KMM)=KAAAA-( (1-ISIGN(1,KMM-3))/2 )
NZZMM(KMM)=KMM+6*(1-ISIGN(1,KMM-3))
RJUDAT(KAAAA,KMM,KDD)=1720994.5_JPRB + REAL( &
     &   2-NZZAA(KAAAA,KMM)/100 + (NZZAA(KAAAA,KMM)/100)/4 &
     & + INT(365.25*REAL(NZZAA(KAAAA,KMM),JPRB)) &
     & + INT(30.601_JPRB*REAL(NZZMM(KMM)+1),JPRB) + KDD,JPRB)
RTIME(KAAAA,KMM,KDD,KSS)=(RJUDAT(KAAAA,KMM,KDD)-2451545._JPRB) &
     & *RDAY+REAL(KSS,JPRB)
!    -------------------------------------------------------------
!=======================================================================

RDAY=86400._JPRB
!
ZPI=2.0_JPRB*ASIN(1.0_JPRB)
!
!     1. READS AND DECODES FINAL OROGRAPHY AND LSM
!
!     1.1 READS DATA
!
LLMAL=.FALSE.
IARG=0
ILAKE=0
LLSEAS=.FALSE.
LLAMIPSST=.FALSE.
LLONEZSST=.FALSE.
LLREADZSST=.TRUE.
YINICE="none"
YINPF1="none"
YINPF2="none"
YINPF3="none"
YINPF4="none"

! Crack options

GET_LOOP:DO
  OPTVAL = GETOPT(OPTIONS,ARG)
  IF(OPTVAL <= 0) THEN
    IF(IARG == 0) THEN
      PRINT *,'NO OPTION SUPPLIED ...'
      CALL USE_INTSST
      CALL ABOR1(' NO OPTIONS SUPPLIED')
    ENDIF
    EXIT
  ENDIF
  OPTLET=CHAR(OPTVAL)
  IF(OPTLET == 's') THEN
    IARG=IARG+1
    READ(UNIT=ARG,FMT='(A128)') YINPF1
  ELSEIF(OPTLET == 'g') THEN
    IARG=IARG+1
    READ(UNIT=ARG,FMT='(A128)') YINPF2
  ELSEIF(OPTLET == 'z') THEN
    IARG=IARG+1
    READ(UNIT=ARG,FMT='(A128)') YINPF3
  ELSEIF(OPTLET == 'o') THEN
    IARG=IARG+1
    READ(UNIT=ARG,FMT='(A128)') YOUTF
  ELSEIF(OPTLET == 'a') THEN
    IARG=IARG+1
    READ(UNIT=ARG,FMT='(A128)') YINPF4
    LLMAL=.TRUE.
    ! Grib codes corresponding to broadband albedo, MODIS albedo
    ! components, leaf area index, sea ice and soil temperature (alb
    ! aluvp aluvd alnip alnid aluvi aluvv aluvg alnii alniv alnig
    ! lai_lv lai_hv stl1 ci)
   ICODEMO(:)=(/174,15,16,17,18, &
         &  210186,210187,210188,210189,210190,210191, &
         &  66,67,139,31/)
  ELSEIF(OPTLET == 'D') THEN
    IARG=IARG+1
    READ(UNIT=ARG,FMT='(I8.8)') IDATE
    LLSEAS=.TRUE.
  ELSEIF(OPTLET == 'E') THEN
    IARG=IARG+1
    READ(UNIT=ARG,FMT='(I8.8)') IDATE
    LLSEAS=.TRUE.
    ILAKE=2
  ELSEIF(OPTLET == 'S') THEN
    IARG=IARG+1
    READ(UNIT=ARG,FMT='(I10)') ISTEP
  ELSEIF(OPTLET == 'i') THEN
    IARG=IARG+1
    READ(UNIT=ARG,FMT='(A)') YINICE
    IF (TRIM(YINICE) /= 'none' .AND. TRIM(YINICE) /= 'use'  &
        & .AND. TRIM(YINICE) /= 'create') THEN
      PRINT *,'OPTION -i ',TRIM(YINICE),'   USED'
      PRINT *,'OPTION -i use OR -i create ONLY'
      CALL ABOR1(' ILLEGAL ARGUMENT FOR OPTION -i')
    ENDIF
  ELSEIF(OPTLET == 'A') THEN
    IARG=IARG+1
    LLAMIPSST=.TRUE.
  ELSEIF(OPTLET == 'O') THEN
    IARG=IARG+1
    LLONEZSST=.TRUE.
  ELSEIF(OPTLET == '?') THEN
    CALL USE_INTSST
    STOP
  ELSE
    PRINT *, ' ILLEGAL OPTION: -',OPTLET
    CALL ABOR1(' ILLEGAL OPTION FOR INTSST')
  ENDIF
ENDDO GET_LOOP   

IF (.NOT.LLSEAS) THEN
  IF (.NOT. LLAMIPSST) THEN
    CALL GRIB_OPEN_FILE(INZLSMF,YINPF3,'R',IRET)
    IF ( IRET /= GRIB_SUCCESS ) THEN
      PRINT *, ' ERROR OPENING ZLSM GRIBFILE ',YINPF3,' IRET= ',IRET
      CALL ABOR1(' ERROR OPENING ZLSM FILE')
    ENDIF
  ENDIF

  CALL GRIB_OPEN_FILE(INSSTF,YINPF1,'R',IRET)
  IF ( IRET /= GRIB_SUCCESS ) THEN
    PRINT *, ' ERROR OPENING SST GRIBFILE ',YINPF1,' IRET= ',IRET
    CALL ABOR1(' ERROR OPENING SST FILE')
  ENDIF

  CALL GRIB_OPEN_FILE(INSFCF,YINPF2,'R',IRET)
  IF ( IRET /= GRIB_SUCCESS ) THEN
    PRINT *, ' ERROR OPENING SFC GRIBFILE ',YINPF2,' IRET= ',IRET
    CALL ABOR1(' ERROR OPENING SFC FILE')
  ENDIF
ENDIF

IF (LLMAL) THEN
  CALL GRIB_OPEN_FILE(INMALF,YINPF4,'R',IRET)
  IF ( IRET /= GRIB_SUCCESS ) THEN
    PRINT *, ' ERROR OPENING MON_ALB GRIBFILE ',YINPF4,' IRET= ',IRET
    CALL ABOR1(' ERROR OPENING MON_ALB FILE')
  ENDIF
ENDIF

IF (TRIM(YINICE) == 'use') THEN
  ICLAN=2
ELSE
  ICLAN=1
ENDIF
 
CALL GRIB_OPEN_FILE(IOUTF,YOUTF,'W',IRET)
IF ( IRET /= GRIB_SUCCESS ) THEN
  PRINT *,'(ERROR OPENING OUTPUT FILE) IRET= ',IRET
  CALL ABOR1(' ERROR OPENING OUTPUT FILE')
ENDIF

IF (.NOT.LLSEAS) THEN
  JFI=0
  READ_LOOP_1:DO 
    JFI=JFI+1
    CALL GRIB_NEW_FROM_FILE(INSFCF,INSFC,IRET)
    IF ( IRET /= GRIB_SUCCESS ) THEN
      IF ( IRET == GRIB_END_OF_FILE ) THEN
        EXIT READ_LOOP_1
      ELSE
        PRINT *,' IRET= ',IRET
        CALL ABOR1(' ERROR READING SFC FILE')
      ENDIF
    ENDIF  

!     1.2 STORES RESOLUTION INFORMATION

    IF (JFI == 1) THEN
      CALL GRIB_GET(INSFC,'getNumberOfValues',IGGO)
      CALL GRIB_GET(INSFC,'PLPresent',IPLP)
      CALL GRIB_GET(INSFC,'Nj',IGLO)
      IF (.NOT. ALLOCATED(ILNO)) THEN
        ALLOCATE(ILNO(IGLO))
      ENDIF
      IF (IPLP == 1) THEN
        CALL GRIB_GET(INSFC,'pl',ILNO)
      ELSE
        CALL GRIB_GET(INSFC,'Ni',IGLA)
        ILNO(:) = IGLA
      ENDIF
      IGLONO=MAXVAL(ILNO)

      IF (.NOT. ALLOCATED(XO)) THEN
        ALLOCATE(XO(IGGO))
        ALLOCATE(SLMO(IGLONO,IGLO))
        ALLOCATE(STO(IGLONO,IGLO))
        ALLOCATE(ZO(IGLONO,IGLO))
        ALLOCATE(CO(IGLONO,IGLO))
        ALLOCATE(ZOZERO(IGLONO,IGLO))
        ALLOCATE(XCO(IGGO))
        ALLOCATE(ZLTO(IGLO))
      ENDIF

      CALL GRIB_GET(INSFC,'latitudeOfFirstGridPointInDegrees',ZLATO)
      ZLATI=-2.0_JPRB*ZLATO/REAL(IGLO-1,JPRB)
      DO J=1,IGLO
        ZLTO(J)=ZLATO+REAL(J-1,JPRB)*ZLATI
      ENDDO

      CALL GRIB_CLONE(INSFC,INSFC1)
    ENDIF

    CALL GRIB_GET(INSFC,'paramId',IPAR)
    CALL GRIB_GET(INSFC,'values',XO)
    IF(IRET /= GRIB_SUCCESS) THEN
      PRINT *, 'DECODE INSFC IRET= ',IRET
      CALL ABOR1(' DECODE')
    ENDIF
    CALL GRIB_RELEASE(INSFC)
!
!     1.3 TRANSFORMS INTO 2D ARRAY
!
    IF (IPAR == 129) THEN
      CALL AR2D(XO,IGGO,ILNO,IGLO,IGLONO,ZO)
      ZOZERO(:,:)=0.0_JPRB
    ELSEIF (IPAR == 172) THEN
      CALL AR2D(XO,IGGO,ILNO,IGLO,IGLONO,SLMO)
    ENDIF
  ENDDO READ_LOOP_1 
ENDIF
 
!            1.4     READ FIRST RECORD OF MONTHLY ALBEDO

IF (LLMAL) THEN
  CALL GRIB_NEW_FROM_FILE(INMALF,INMAL,IRET)
  IF (IRET /= GRIB_SUCCESS) THEN
    PRINT '(''ERROR READING MONTHLY ALBEDO FILE, IRET = '',I10)' ,IRET
    CALL ABOR1('')
  ENDIF

  CALL GRIB_GET(INMAL,'dataTime',INTIME)
  IHH = INTIME/100
  ISS=3600*IHH
  CALL GRIB_GET(INMAL,'dataDate',INDATE)
  IYY = NYYYY(INDATE)
  IMM = NMM(INDATE)
  IDD = NDD(INDATE)

!            1.5     UNPACK HEADER RECORDS TO DETERMINE DATA LENGTHS

  CALL GRIB_GET(INMAL,'getNumberOfValues',LEN,IRET)
  IF (IRET /= GRIB_SUCCESS) THEN
    PRINT '(''ERROR DECODING FIRST MONTHLY CLIMATE FILE RECORD'')'
    PRINT '(''IRET = '',I10)', IRET
    CALL ABOR1('')
  ENDIF

!            1.6     ALLOCATE ARRAYS DYNAMICALLY


  ALLOCATE(CLIM(LEN,JMON,JPCLIM+2))
  ALLOCATE(EXPT(LEN))
  ALLOCATE(ZSEC4(LEN))

  IFOUNDFI=0

  CALL GRIB_CLONE(INMAL,IOUT)

!            1.7     LOOP OVER CLIMATE FILE, READING GRIB RECORDS

  ICLMON=JMON*(JPCLIM+ILAKE)
  PRINT '('' ICLMON, JMON, JPCLIM = '',3I5)', ICLMON,JMON,JPCLIM

!  DO J=1,JPCLIM
     SCAN:DO
      IF ( .NOT.LLFIRST ) THEN
        CALL GRIB_NEW_FROM_FILE(INMALF,INMAL,IRET)
	PRINT '('' IFOUNDFI,INMAL,IRET = '',5I10)',IFOUNDFI,INMAL,IRET 
        IF (IRET /= GRIB_SUCCESS) THEN
          IF (IRET == GRIB_END_OF_FILE) THEN
            IF (IFOUNDFI == ICLMON ) EXIT SCAN
            PRINT '(''EOF DETECTED ON MONTHLY ALBEDO FILE'')'
            PRINT '(''NUMBER OF FIELDS LOCATED = '',I10)', IFOUNDFI
            PRINT '(''NUMBER OF FIELDS REQUIRED = '',I10)', ICLMON
	    CALL ABOR1('')
          ELSE
            PRINT '(''ERROR READING MONTHLY ALBEDO FILE'')'
            PRINT '(''IRET = '',I10)', IRET
            CALL ABOR1('')
          ENDIF
        ENDIF
      ENDIF
      LLFIRST=.FALSE.

!            1.8     DECODE GRIB

      CALL GRIB_GET(INMAL,'paramId',ICODE,IRET)
      IF (IRET  /=  0) THEN
        PRINT '(''ERROR DECODING MONTHLY CLIMATE GRIB RECORD'')'
        PRINT '(''IRET = '',I10)', IRET
        CALL ABOR1('')
      ENDIF

!            1.9     STORE MONTHLY CLIMATE DATA VALUES IN ARRAY CLIM


      DO J=1,JPCLIM+ILAKE
        IF (ICODEMO(J) == ICODE) THEN
          IGRBC=ICODE
          CALL GRIB_GET(INMAL,'dataDate',INDATE)
          IMO = NMM(INDATE)
          CALL GRIB_GET(INMAL,'values',ZSEC4)
          IF ( J == JPCLIM+1 .AND. ILAKE > 0 ) THEN
             CALL GRIB_CLONE(INMAL,IOUT1)
          ENDIF
          CLIM(:,IMO,J)=ZSEC4(1:LEN)
          ICLIMCOD(IMO,J)=IGRBC
          IFOUNDFI=IFOUNDFI+1
        ENDIF
      ENDDO
      CALL GRIB_RELEASE(INMAL)
    ENDDO SCAN
!  ENDDO
ENDIF

!  CREATES A CONSECUTIVE SET OF MONTHLY FILES, SPANNING THE INTEGRATION
!  PERIOD, IN CASE OF A SEASONAL RUN

IF (LLSEAS) THEN

!         FIND FIRST YEAR_MONTH NEEDED

  IMM=NMM(IDATE)
  IMB=MOD(IMM+10,12)+1
  IYB=NYYYY(IDATE)
  IF (IMB == 12) IYB=IYB-1
  IMM=IMB
  IYY=IYB
!       FIND JULIAN DATE CORRESPONDING TO LAST YEAR_MONTH NEEDED
  ZJDB=RJUDAT(NYYYY(IDATE),NMM(IDATE),NDD(IDATE))
!       ADD INTEGRATION PERIOD PLUS TWO MONTHS FOR INTERPOLATION AT THE END
  ZJDE=ZJDB+REAL(ISTEP,JPRB)/24._JPRB+62._JPRB
!       SCAN THROUGH THE MONTHS
  DO
    ZJD=RJUDAT(IYY,IMM,1)
    IF (ZJD > ZJDE) EXIT

!            1.10     ENCODE GRIB

    IDATE = IYY*10000 + IMM*100 + IDD
    CALL GRIB_SET(IOUT,'dataDate',IDATE)

    DO J=1,JPCLIM
      CALL GRIB_SET(IOUT,'paramId',ICLIMCOD(IMM,J))
      CALL GRIB_SET(IOUT,'values',CLIM(1:LEN,IMM,J),IRET)
       
      IF (IRET /= GRIB_SUCCESS) THEN
        PRINT '(''ERROR ENCODING MONTHLY CLIMATE ALBEDO'')'
        PRINT '(''IRET = '',I10)', IRET
        CALL ABOR1('')
      ENDIF
!            1.11    WRITE MODIFIED GRIB RECORD TO FILE _MON_OUT

      CALL GRIB_WRITE(IOUT,IOUTF,IRET)
      IF (IRET /= GRIB_SUCCESS) THEN
        PRINT '(''ERROR WRITING GRIB RECORD'')'
        PRINT '(''IRET = '',I10)', IRET
        PRINT '(''ICODE = '',I10)', ICODE
        CALL ABOR1('')
      ENDIF
    ENDDO

    IF ( ILAKE > 0 ) THEN
       CALL GRIB_SET(IOUT1,'dataDate',IDATE)
       DO J=JPCLIM+1,JPCLIM+ILAKE
          CALL GRIB_SET(IOUT1,'paramId',ICLIMCOD(IMM,J))
          CALL GRIB_SET(IOUT1,'values',CLIM(1:LEN,IMM,J),IRET)

          IF (IRET /= GRIB_SUCCESS) THEN
             PRINT '(''ERROR ENCODING MONTHLY LAKE CLIMATOLOGY'')'
             PRINT '(''IRET = '',I10)', IRET
             CALL ABOR1('')
           ENDIF
!            1.11    WRITE MODIFIED GRIB RECORD TO FILE _MON_OUT

          CALL GRIB_WRITE(IOUT1,IOUTF,IRET)
          IF (IRET /= GRIB_SUCCESS) THEN
             PRINT '(''ERROR WRITING GRIB RECORD'')'
             PRINT '(''IRET = '',I10)', IRET
             PRINT '(''ICODE = '',I10)', ICODE
             CALL ABOR1('')
          ENDIF
       ENDDO
    ENDIF
          
!         FIND NEXT YEAR_MONTH
    IMM=IMM+1
    IF (IMM == 13) IMM=1
    IF (IMM == 1) IYY=IYY+1
  ENDDO
  STOP

ENDIF

!
!     2. SCANS THROUGH THE INPUT FIELDS
!
READ_LOOP_2: DO

!     2.1 READS ORO AND LSM OF THE INPUT GRID

  IF (.NOT. LLAMIPSST.AND.LLREADZSST) THEN
    DO JFI=1,2
      CALL GRIB_NEW_FROM_FILE(INZLSMF,INZLSM,IRET)

      IF (IRET /= GRIB_SUCCESS) THEN
        IF (IRET == GRIB_END_OF_FILE) THEN
          EXIT READ_LOOP_2
        ELSE
          PRINT *,' IRET= ',IRET
          CALL ABOR1('')
        ENDIF
      ENDIF

!     2.2 STORES RESOLUTION INFORMATION

      IF (JFI == 1) THEN
        CALL GRIB_GET(INZLSM,'getNumberOfValues',IGGI)
        CALL GRIB_GET(INZLSM,'Nj',IGLI)
        CALL GRIB_GET(INZLSM,'PLPresent',IPLP)
        IF (.NOT. ALLOCATED(ILNI)) THEN
          ALLOCATE(ILNI(IGLI))
        ENDIF
        IF (IPLP == 1) THEN
          CALL GRIB_GET(INZLSM,'pl',ILNI)
        ELSE
          CALL GRIB_GET(INZLSM,'Ni',IGLA)
          ILNI(:) = IGLA
        ENDIF
        IGLONI = MAXVAL(ILNI)

        IF (.NOT. ALLOCATED(XI)) THEN
          ALLOCATE(XI(IGGI))
          ALLOCATE(SLMI(IGLONI,IGLI))
          ALLOCATE(STI(IGLONI,IGLI))
          ALLOCATE(ZI(IGLONI,IGLI))
          ALLOCATE(CI(IGLONI,IGLI))
          ALLOCATE(ZIZERO(IGLONI,IGLI))
          ALLOCATE(ZLTI(IGLI))        
        ENDIF

        CALL GRIB_GET(INZLSM,'latitudeOfFirstGridPointInDegrees',ZLATO)      
        ZLATI=-2.0_JPRB*ZLATO/REAL(IGLI-1,JPRB)
        DO JG=1,IGLI
          ZLTI(JG)=ZLATO+REAL(JG-1,JPRB)*ZLATI
        ENDDO
      ENDIF

      CALL GRIB_GET(INZLSM,'paramId',IPAR)
      CALL GRIB_GET(INZLSM,'values',XI,IRET)
      IF(IRET /= GRIB_SUCCESS) THEN
        PRINT *, ' DECODE INZLSM IRET= ',IRET
        CALL ABOR1(' DECODE')
      ENDIF
      CALL GRIB_RELEASE(INZLSM)

!     2.3 TRANSFORMS ORO AND LSM INTO 2D ARRAY

      IF (IPAR == 129) THEN
        CALL AR2D(XI,IGGI,ILNI,IGLI,IGLONI,ZI)
        ZIZERO(:,:)=0.0_JPRB
      ELSEIF (IPAR == 172) THEN
        CALL AR2D(XI,IGGI,ILNI,IGLI,IGLONI,SLMI)
      ENDIF
    ENDDO
    IF (LLONEZSST) LLREADZSST=.FALSE.
  ENDIF

!     2.4 READS SST AND POSSIBLY SEA-ICE DATA

  CLAN: DO JCAN=1,ICLAN
    CALL GRIB_NEW_FROM_FILE(INSSTF,INSST,IRET)
       
    IF (IRET /= GRIB_SUCCESS) THEN
      IF (IRET == GRIB_END_OF_FILE) THEN
        EXIT READ_LOOP_2
      ELSE
        PRINT *,' IRET= ',IRET
        CALL ABOR1('')
      ENDIF
    ENDIF

    CALL GRIB_GET(INSST,'dataDate',ISDATE)
    CALL GRIB_GET(INSST,'dataTime',ISTIME)
    CALL GRIB_GET(INSST,'paramId',IPAR)
    CALL GRIB_GET(INSST,'getNumberOfValues',IGGI)

    IF (LLAMIPSST .AND. IGGI /= IGGO) THEN
      PRINT *,' OUTPUT AND INPUT RESOLUTIONS ARE DIFFERENT'
      CALL ABOR1('')
    ENDIF

    CALL GRIB_SET(INSST,'missingValue',0.0_JPRB)
    CALL GRIB_GET(INSST,'values',XI,IRET)
    
    IF(IRET /= GRIB_SUCCESS) THEN
      PRINT *, ' DECODE INSST IRET= ',IRET
      CALL ABOR1(' DECODE')
    ENDIF

    IF(JCAN.EQ.ICLAN) THEN
      PRINT *, 'SST read for dataDate ',ISDATE
      CALL FLUSH(6)
    ENDIF

!     2.5 TRANSFORMS ST INTO 2D ARRAY

    IF (IGGI /= IGGO) THEN
      IF (IPAR == 139) THEN
        CALL AR2D(XI,IGGI,ILNI,IGLI,IGLONI,STI)

!     2.6 INTERPOLATE ST

        CALL INTER(IGLI,IGLONI,IGLO,IGLONO,ILNO,ILNI, &
                & ZLTO,STI,SLMI,SLMO,ZI,ZO,STO)

!  CLIP OCEAN VALUES TO REALISTIC VALUES, TO AVOID LSM INCOMPATIBILITIES
        RTT=273.16_JPRB
        RTUPPER=RTT+40._JPRB
        DO JG=1,IGLO
          DO JL=1,ILNO(JG)
            IF (SLMO(JL,JG) <= 0.5_JPRB) THEN
              STO(JL,JG)=MIN(RTUPPER,STO(JL,JG))
            ENDIF
          ENDDO
        ENDDO


!     2.7 TRANSFORM ST INTO 1D ARRAY

        CALL AR1D(STO,IGLO,IGLONO,ILNO,LEN,XO,IGGO)
      ELSEIF (IPAR == 31) THEN
        CALL AR2D(XI,IGGI,ILNI,IGLI,IGLONI,CI)

!         INTERPOLATE SEA-ICE

        CALL INTER(IGLI,IGLONI,IGLO,IGLONO,ILNO,ILNI, &
              & ZLTO,CI,SLMI,SLMO,ZIZERO,ZOZERO,CO)

        CALL AR1D(CO,IGLO,IGLONO,ILNO,LEN,XO,IGGO)
      ENDIF
    ELSE
      CALL AR2D(XI,IGGO,ILNO,IGLO,IGLONO,STO)

!  CLIP OCEAN VALUES TO REALISTIC VALUES, TO AVOID LSM INCOMPATIBILITIES

      IF (IPAR == 139) THEN
        RTT=273.16_JPRB
        RTUPPER=RTT+40._JPRB
        DO JG=1,IGLO
          DO JL=1,ILNO(JG)
            IF (SLMO(JL,JG) <= 0.5_JPRB) THEN
              STO(JL,JG)=MIN(RTUPPER,STO(JL,JG))
            ENDIF
          ENDDO
        ENDDO
      ENDIF
      CALL AR1D(STO,IGLO,IGLONO,ILNO,LEN,XO,IGGO)
    ENDIF

! CREATES PROXY FOR SEA-ICE FRACTION

    IF (TRIM(YINICE) == 'create') THEN
      RTT=273.16_JPRB
      RTFREEZ=RTT-1.7_JPRB
      DO JG=1,IGLO
        DO JL=1,ILNO(JG)
          IF (STO(JL,JG) < RTFREEZ .AND. SLMO(JL,JG) <= 0.5_JPRB) THEN
            CO(JL,JG)=1.0_JPRB
          ELSE
            CO(JL,JG)=0.0_JPRB
          ENDIF
        ENDDO
      ENDDO

      CALL AR1D(CO,IGLO,IGLONO,ILNO,LEN,XCO,IGGO)

      CALL GRIB_UTIL_SECTIONS_COPY(INSFC1,INSST,GRIB_SECTION_GRID,IOUT)
      CALL GRIB_SET(IOUT,'bitmapPresent',0)
      CALL GRIB_SET(IOUT,'paramId',31)
      CALL GRIB_SET(IOUT,'values',XCO,IRET)
      IF (IRET /= GRIB_SUCCESS) THEN
        PRINT '(''ERROR ENCODING SEA-ICE'')'
        PRINT '(''IRET = '',I10)', IRET
        CALL ABOR1('')
      ENDIF

      CALL GRIB_WRITE(IOUT,IOUTF,IRET)
      IF (IRET /= GRIB_SUCCESS) THEN
        PRINT '(A,I3)', ' RETURN CODE FOR GRIB_WRITE',IRET
        CALL ABOR1('')
      ENDIF
    ENDIF

!     2.8 GRIB CODE AND WRITE

    CALL GRIB_UTIL_SECTIONS_COPY(INSFC1,INSST,GRIB_SECTION_GRID,IOUT)
    CALL GRIB_SET(IOUT,'bitmapPresent',0)
    CALL GRIB_SET(IOUT,'values',XO,IRET)
    IF (IRET /=  GRIB_SUCCESS) THEN
      PRINT '(''ERROR ENCODING PARAMETER'',I10)', IPAR
      PRINT '(''IRET = '',I10)', IRET
      CALL ABOR1('')
    ENDIF
    CALL GRIB_RELEASE(INSST)

    CALL GRIB_WRITE(IOUT,IOUTF,IRET)
    IF (IRET /= GRIB_SUCCESS) THEN
      PRINT '(A,I3)', ' RETURN CODE FOR GRIB_WRITE',IRET
      CALL ABOR1('')
    ENDIF
  ENDDO CLAN

!          2.9        INTERPOLATE IN TIME TO DATE IYYMDH

  IF (LLMAL) THEN
    IHH = ISTIME/100
    ISS=3600*IHH
    IYY = NYYYY(ISDATE)
    IMM = NMM(ISDATE)
    IDD = NDD(ISDATE)

    IF (IDD .GE. 15) THEN
      IMT1=IMM
      IMT2=1+MOD(IMM,12)
      IYT1=IYY
      IF(IMT2 == 1) THEN
        IYT2=IYT1+1
      ELSE
        IYT2=IYT1
      ENDIF
    ELSE
      IMT1=1+MOD(IMM+10,12)
      IMT2=IMM
      IF(IMT1 == 12) THEN
        IYT1=IYY-1
      ELSE
        IYT1=IYY
      ENDIF
      IYT2=IYY
    ENDIF
    ZT1=RTIME(IYT1,IMT1,15,0)
    ZT2=RTIME(IYT2,IMT2,15,0)

    ZT=RTIME(IYY,IMM,IDD,ISS)
    ZWEI1=(ZT2-ZT)/(ZT2-ZT1)
    ZWEI2=1.0_JPRB-ZWEI1

    DO J=1,JPCLIM
      EXPT(:)=ZWEI1*CLIM(:,IMT1,J)+ZWEI2*CLIM(:,IMT2,J)

!            2.10     ENCODE GRIB

      CALL GRIB_SET(IOUT,'dataDate',IYY*10000 + IMM*100 + IDD)
      CALL GRIB_SET(IOUT,'dataTime',ISTIME)
      CALL GRIB_SET(IOUT,'paramId',ICODEMO(J))

      CALL GRIB_SET(IOUT,'values',EXPT(1:LEN),IRET)
      IF (IRET /= GRIB_SUCCESS) THEN
        PRINT '(''ERROR ENCODING ALBEDO'')'
        PRINT '(''IRET = '',I10)', IRET
        CALL ABOR1('')
      ENDIF

!            2.11    WRITE MODIFIED GRIB RECORD TO FILE _MON_OUT

      CALL GRIB_WRITE(IOUT,IOUTF,IRET)
      IF (IRET /=  GRIB_SUCCESS) THEN
        PRINT '(''ERROR WRITING GRIB RECORD'')'
        PRINT '(''IRET = '',I10)', IRET
        PRINT '(''ICODE = '',I10)', ICODEMO(J)
        CALL ABOR1('')
      ENDIF
    ENDDO
  ENDIF

ENDDO READ_LOOP_2

CALL GRIB_CLOSE_FILE(IOUTF,IRET)
IF (IRET /= GRIB_SUCCESS) THEN
  PRINT '(A,I3)', ' RETURN CODE FOR GRIB_CLOSE',IRET
  CALL ABOR1('')
ENDIF

STOP


