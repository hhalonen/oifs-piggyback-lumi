SUBROUTINE AR2D(PX,KGG,KLN,KGL,KLON,P2)

!     GOES FROM A CONTIGUOUS 1D ARRAY TO A 2D ARRAY

!     INPUT:  PX    REAL ARRAY                                        (KGG)
!             KGG   INTEGER DIMENSION OF ARRAY PX
!             KLN   INTEGER ARRAY NUMBER OF POINTS IN A LATITUDE ROW  (KGL)
!             KGL   INTEGER NUMBER OF LATITUDE ROWS
!             KLON  INTEGER MAXIMUM NUMBER OF POINTS IN A LATITUDE ROW

!     OUTPUT: P2    REAL ARRAY                                   (KLON,KGL)

REAL(KIND=JPRB) :: PX(KGG),P2(KLON,KGL)
INTEGER(KIND=JPIM) :: KLN(KGL), KGG, KGL, KLON, IPOI

IPOI=0
DO JG=1,KGL
  DO JL=1,KLN(JG)
    IPOI=IPOI+1
    P2(JL,JG)=PX(IPOI)
  ENDDO
ENDDO

RETURN

END  SUBROUTINE AR2D

SUBROUTINE AR1D(P2,KGL,KLON,KLN,KLEN,PX,KGG)

!     GOES FROM A 2D ARRAY TO A CONTIGUOUS 1D ARRAY

!     INPUT:  P2    REAL ARRAY                                   (KLON,KGL)
!             KGG   INTEGER DIMENSION OF ARRAY PX
!             KLN   INTEGER ARRAY NUMBER OF POINTS IN A LATITUDE ROW  (KGL)
!             KGL   INTEGER NUMBER OF LATITUDE ROWS
!             KLON  INTEGER MAXIMUM NUMBER OF POINTS IN A LATITUDE ROW

!     OUTPUT: PX    REAL ARRAY                                       (KLEN)
!             KGG   INTEGER  NUMBER OF POINTS IN PX                   (KGG)

REAL(KIND=JPRB) :: PX(KLEN),P2(KLON,KGL)
INTEGER(KIND=JPIM) :: KLN(KGL), KGG, KGL, KLEN, KLON,  IPOI

IPOI=0
DO JG=1,KGL
  DO JL=1,KLN(JG)
    IPOI=IPOI+1
    PX(IPOI)=P2(JL,JG)
  ENDDO
ENDDO
KGG=IPOI

RETURN

END  SUBROUTINE AR1D

SUBROUTINE INTER(KGLI,KLONI,KGLO,KLONO,KLNO,KLNI,&
                   & PLTO,PXI,PSLMI,PSLMO,PORI,PORO,PXO)

!    THIS ROUTINE INTERPOLATES THE SST FROM ONE GG TO ANOTHER

!    METHOD

!      THE SAME AS USED FOR COMPUTING THE OROGRAPHY IN PROGRAM
!       USNAVY OF 'PREPCLIM' SYSTEM

!     INPUT: KGLI    INTEGER  NUMBER OF GAUSSIAN LATITUDES OF INPUT GRID
!            KLONI   INTEGER  MAX NUMBER OF POINTS IN A LAT ROW OF INPUT GRID
!            KGLO    INTEGER  NUMBER OF GAUSSIAN LATITUDES OF OUTPUT GRID
!            KLONO   INTEGER  MAX NUMBER OF POINTS IN A LAT ROW OF OUTPUT GRID
!            KLNO    INTEGER ARRAY NUMBER OF POINTS IN A LATITUDE ROW OF
!                                  OUTPUT GRID                       (KGLO)
!            KLNI    INTEGER ARRAY NUMBER OF POINTS IN A LATITUDE ROW OF
!                                  INPUT GRID                        (KGLI)
!            KGLOP1  INTEGER  KGLO+1
!            KLONOP2 INTEGER  KLONO+2
!            KLONIP1 INTEGER  KLONI+1
!            PLTO    REAL ARRAY GAUSSIAN LATITUDES OF OUTPUT GRID    (KGLO)
!            PXI     REAL ARRAY SST ON INPUT GRID              (KLONI,KGLI)
!            PSLMI   REAL ARRAY LAND SEA MASK OF INPUT GRID    (KLONI,KGLI)
!            PSLMO   REAL ARRAY LAND SEA MASK OF OUTPUT GRID   (KLONO,KGLO)
!            PORI    REAL ARRAY OROGRAPHY OF INPUT GRID        (KLONI,KGLI)
!            PORO    REAL ARRAY OROGRAPHY OF OUTPUT GRID       (KLONO,KGLO)

!     OUTPUT:PXO     REAL ARRAY SST ON OUTPUT GRID             (KLONO,KGLO)

INTEGER(KIND=JPIM) :: KGLI, KGLO, KLONI, KLONO
INTEGER(KIND=JPIM) :: KLNO(KGLO),KLNI(KGLI)
REAL(KIND=JPRB) :: PLTO(KGLO),PXI(KLONI,KGLI),PXO(KLONO,KGLO),&
          & PSLMI(KLONI,KGLI),PSLMO(KLONO,KGLO),&
          & PORI(KLONI,KGLI),PORO(KLONO,KGLO)

REAL(KIND=JPRB) :: ZLTBO(KGLO+1),ZLWE(KLONO+2),ZORII(KLONO),ZXO(KLONO),ZTWT(KLONO),&
          & ZBE(KLONI+1),ZBW(KLONI+1),ZFAC(KLONI+1)
REAL(KIND=JPRB) :: ZG, ZRTC, ZPLN, ZPLS, ZBN, ZBS, ZNSWT, ZPLW, ZPLE, ZWEWT
REAL(KIND=JPRB) :: ZLWT, ZFLDW, ZCORTS, ZEPSILON
INTEGER(KIND=JPIM) :: IREAD, IUSN, JRO, IPNT, IPNTP1, IPNTP2, IL, JU, IU, IJL

!     1.  GRID RELATED QUANTITIES AND CONSTANTS

ZPI=2.0_JPRB*ASIN(1.0_JPRB)
ZG=9.80665_JPRB
ZEPSILON=1.E-5_JPRB
ZRTC=.65_JPRB/100._JPRB        !RATE OF TEMPERATURE CHANGE WITH HEIGHT
!     LATITUDE BOUNDARIES FOR TARGET GRID
ZLTBO(1)=0.0_JPRB
DO J=2,KGLO
  ZLTBO(J)=0.5_JPRB*(1.0_JPRB-0.5_JPRB*(SIN(PLTO(J)*ZPI/180._JPRB)+ &
           & SIN(PLTO(J-1)*ZPI/180._JPRB)))
ENDDO
ZLTBO(KGLO+1)=1.0_JPRB

!     2.  LOOP FOR THE TARGET GRID

IREAD=1
IUSN=0

!$OMP PARALLEL DO PRIVATE(JRO,IPNT,IPNTP1,IPNTP2,ZPLN,ZPLS,J,ZLWE,ZORII,ZXO,ZTWT) &
!$OMP& PRIVATE(ZBN,ZBS,ZBW,ZBE,ZNSWT,JL,ZPLW,ZPLE,IL,JU,IU,ZFAC,ZWEWT) &
!$OMP& PRIVATE(ZLWT,ZFLDW,ZCORTS,IJL) &
!$OMP& FIRSTPRIVATE(IREAD,IUSN)
OUTG_LOOP: DO JRO=1,KGLO

!     2.1  PRELIMINARY INFO FOR THE PRESENT ROW

  IPNT=KLNO(JRO)
!      PRINT *,'   TARGET GRID ROW=',JRO,'  N. OF POINTS=',IPNT
  IPNTP1=IPNT+1
  IPNTP2=IPNT+2
!       LATITUDE BOUNDARIES FOR THE PRESENT OUTPUT ROW
  ZPLN=ZLTBO(JRO)
  ZPLS=ZLTBO(JRO+1)
!       LONGITUDE BOUNDARIES FOR EACH POINT OF THE PRESENT ROW
!        WITH ONE POINT OF WRAP-AROUND
  DO J=1,IPNTP2
    ZLWE(J)=(J-1.5_JPRB)/REAL(IPNT,JPRB)
  ENDDO
  ZORII(1:IPNT)=0.0_JPRB
  ZXO(1:IPNT)=0.0_JPRB
  ZTWT(1:IPNT)=0.0_JPRB

!       2.2   LOOP FOR THE INPUT GRID

  ING_LOOP: DO
    IF(IREAD == 1) THEN
      IUSN=IUSN+1
      ZBN=0.5_JPRB*(1.0_JPRB-COS(ZPI*(IUSN-1)/REAL(KGLI,JPRB)))
      ZBS=0.5_JPRB*(1.0_JPRB-COS(ZPI*IUSN/REAL(KGLI,JPRB)))
!        LONGITUDINAL BOUNDARIES FOR INPUT GRID
      DO J=1,KLNI(IUSN)+1
        ZBW(J)=(J-1.5_JPRB)/REAL(KLNI(IUSN),JPRB)
        ZBE(J)=(J-0.5_JPRB)/REAL(KLNI(IUSN),JPRB)
      ENDDO
      ZBW(1)=0.0_JPRB
      ZBE(KLNI(IUSN)+1)=1.0_JPRB
!         PRINT *,'  READ ROW ',IUSN,' OF INPUT FILE'
    ENDIF
    ZNSWT=(MAX(ZPLN,MIN(ZPLS,ZBS))-MIN(ZPLS,MAX(ZPLN,ZBN)))/(ZPLS-ZPLN)

!     2.3  LOOP OVER POINTS OF OUTPUT GRID

    DO JL=1,IPNTP1
      ZPLW=ZLWE(JL)
      ZPLE=ZLWE(JL+1)
      IL=JL
      IF(JL == IPNTP1) IL=1
      DO JU=1,KLNI(IUSN)+1
        IU=JU
        IF(JU == KLNI(IUSN)+1) IU=1
        IF((PSLMO(IL,JRO) > 0.5_JPRB .AND. PSLMI(IU,IUSN) > 0.5_JPRB) &
          & .OR.(PSLMO(IL,JRO) <= 0.5_JPRB .AND. PSLMI(IU,IUSN) <= 0.5_JPRB)) THEN
          ZFAC(IU)=1.0_JPRB
        ELSE
          ZFAC(IU)=0.2_JPRB
        ENDIF
      ENDDO
      DO JU=1,KLNI(IUSN)
        IU=JU
        ZWEWT=(MAX(ZPLW,MIN(ZPLE,ZBE(JU)))- &
            &  MIN(ZPLE,MAX(ZPLW,ZBW(JU))))/(ZPLE-ZPLW)
        ZLWT=ZWEWT*ZNSWT*ZFAC(IU)
        ZTWT(IL)=ZTWT(IL)+ZLWT
        ZORII(IL)=ZORII(IL)+PORI(IU,IUSN)*ZLWT
        ZFLDW=PXI(IU,IUSN)*ZLWT
        ZXO(IL)=ZXO(IL)+ZFLDW
      ENDDO
      JU=KLNI(IUSN)+1
      IU=1
      ZWEWT=(MAX(ZPLW,MIN(ZPLE,ZBE(JU)))- &
          &  MIN(ZPLE,MAX(ZPLW,ZBW(JU))))/(ZPLE-ZPLW)
      ZLWT=ZWEWT*ZNSWT*ZFAC(IU)
      ZTWT(IL)=ZTWT(IL)+ZLWT
      ZORII(IL)=ZORII(IL)+PORI(IU,IUSN)*ZLWT
      ZFLDW=PXI(IU,IUSN)*ZLWT
      ZXO(IL)=ZXO(IL)+ZFLDW
    ENDDO

!     2.4  OROGRAPHY CORRECTION

    IF(ZBS .GE. ZPLS) THEN
      IJL = MINLOC(ZTWT(1:IPNT),1)
      IF (ZTWT(IJL) <= ZEPSILON) THEN
        PRINT *,'  NULL WEIGHT FOR POINT ',IJL,' OF ROW ',JRO
	CALL ABOR1('')
      ELSE
        DO JL=1,IPNT
          ZORII(JL)=ZORII(JL)/ZTWT(JL)
          ZCORTS=-ZRTC*(PORO(JL,JRO)-ZORII(JL))/ZG
          ZXO(JL)=ZXO(JL)/ZTWT(JL)
          PXO(JL,JRO)=ZXO(JL)+ZCORTS
        ENDDO
      ENDIF
      IREAD=0
      EXIT ING_LOOP
    ENDIF
    IREAD=1
  ENDDO ING_LOOP
ENDDO OUTG_LOOP
!$OMP END PARALLEL DO

END SUBROUTINE INTER

