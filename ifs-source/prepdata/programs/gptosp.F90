PROGRAM GPTOSP

USE PARKIND1, ONLY : JPIM, JPRB

USE MPL_MPIF, ONLY : MPI_COMM_WORLD
USE MPL_MODULE
USE GRIB_API

IMPLICIT NONE

! Should be defined in GRIB_API module
INTEGER, PARAMETER :: GRIB_SECTION_PRODUCT =  1
INTEGER, PARAMETER :: GRIB_SECTION_GRID    =  2
INTEGER, PARAMETER :: GRIB_SECTION_LOCAL   =  4
INTEGER, PARAMETER :: GRIB_SECTION_DATA    =  8
INTEGER, PARAMETER :: GRIB_SECTION_BITMAP  = 16


CHARACTER OPTIONS*24
DATA OPTIONS/'h;g:G:S:T:f:r:e:P:X;l;U;'/
CHARACTER ARG*127,  OPTLET
CHARACTER*127 COUTSF, COUTGPF, CINGPF, CFIELD, CPROC, CFACT, CEXPO, CTRUNC
CHARACTER*127 CGRIDTYPE, CLEVELTYPE, CSAMPLESFILE
CHARACTER*1 CEDITION

INTEGER(KIND=JPIM),PARAMETER :: JPMAXFLD=31

INTEGER(KIND=JPIM) :: ISTACK
INTEGER(KIND=JPIM) :: getstackusage
INTEGER(KIND=JPIM) :: OPTVAL
REAL(KIND=JPRB)    :: Z, FACT, ZFACT, ZFAC

INTEGER(KIND=JPIM) :: NERR,NPROC,NLIN,INSF,ILENG,IOUTLEN,IWORD,NSMAX,NDGL,IGRIBOUT,ISAMPLE
INTEGER(KIND=JPIM) :: NOUT,NSPEC2,NGPTOT,NGPTOTG,IMAXFLD,IFLD,ICODE,IOUTSF,I,ISTRUNC,IEDITION_PREV
INTEGER(KIND=JPIM) :: JROC,IERR,IMLEN,ISENDR,ITAGR,ITAG,NSPEC2G,IRET,JM,JI,II,JN,ISE
INTEGER(KIND=JPIM) :: IOUTGPF,JFLD,JGL,NEXPO,IEXP,ITABLE
INTEGER(KIND=JPIM), DIMENSION(JPMAXFLD+1) :: IPARAM,IGRIB,IEDITION 
INTEGER(KIND=JPIM) ,ALLOCATABLE :: NLOEN(:),ITO(:),NPRCIDS(:)
INTEGER(KIND=JPIM) :: IGRIB_SAVE(JPMAXFLD+1),IIPARAM(JPMAXFLD+1),JPAR
INTEGER(KIND=JPIM) :: GETOPT,MYPROC,JJ
INTEGER(KIND=JPIM) :: IPROC,IPROC_OLD,ICOMM,ICOMM_OLD,ITRUNC
INTEGER(KIND=JPIM) :: INPARS,INLEVS,JLEV,ISF,ILOCALDEF
INTEGER(KIND=JPIM),ALLOCATABLE :: ILEVEL(:),ifsparam(:)
REAL(KIND=JPRB)    :: ZT,TIMEF,ZCODE
REAL(KIND=JPRB),ALLOCATABLE :: ZSPECG(:,:),ZSPEC(:,:),ZFPDAT(:),ZSPVOR(:,:),ZSPDIV(:,:)
REAL(KIND=JPRB),ALLOCATABLE :: ZG(:,:,:),ZGG(:,:)
LOGICAL :: LDONE,LSCAL,LGRIBEX,LVD2UV

integer ia

!     ------------------------------------------------------------------

#include "setup_trans0.h"
#include "setup_trans.h"
#include "dir_trans.h"
#include "dist_grid.h"
#include "gath_spec.h"
#include "trans_inq.h"

! Initializations
NERR = 0
NOUT = 6
IMAXFLD = JPMAXFLD

ia=0

! Set defaults for options

CINGPF   = ' '
COUTSF  = ' '
COUTGPF = ' '
CFIELD  = ' '
IPROC   = 1
ITRUNC  = 0
LSCAL   = .false.
LGRIBEX = .false.
LVD2UV  = .FALSE.
NLIN    = 0
FACT    = 1.0_JPRB
NEXPO   = 4

! Crack options

DO
  OPTVAL = GETOPT(OPTIONS,ARG)
  IF(OPTVAL <= 0) EXIT
  OPTLET=CHAR(OPTVAL)
  IF(OPTVAL <= 0) EXIT
  IF(OPTLET == 'h') THEN
    CALL USE_GPTOSP
    STOP
  ELSEIF(OPTLET == 'g')  THEN
    CINGPF = ARG
  ELSEIF(OPTLET == 'G') THEN
    COUTGPF = ARG
  ELSEIF(OPTLET == 'S') THEN
    COUTSF = ARG
  ELSEIF(OPTLET == 'T') THEN
    CTRUNC = ARG
    READ(CTRUNC,*) ITRUNC
  ELSEIF(OPTLET == 'f') THEN
    CFIELD = ARG
  ELSEIF(OPTLET == 'r') THEN
    CFACT = ARG
    READ(CFACT,*) FACT
  ELSEIF(OPTLET == 'e') THEN
    CEXPO = ARG
    READ(CEXPO,*) NEXPO
  ELSEIF(OPTLET == 'P') THEN
    CPROC = ARG
    READ(CPROC,*) IPROC
  ELSEIF(OPTLET == 'X') THEN
    LGRIBEX = .true.
  ELSEIF(OPTLET == 'l') THEN
    NLIN = 1
  ELSEIF(OPTLET == 'U') THEN
    LVD2UV = .TRUE.
  ELSE
    PRINT *, ' ILLEGAL OPTION: -',OPTLET
    CALL USE_GPTOSP
    CALL ABOR1('GPTOSP:ERROR IN ARGUMENT')
  ENDIF
ENDDO

IF (IPROC == 1) LSCAL=.true.  !-- serial binary ---

!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
LGRIBEX = .TRUE.
!PRINT *, '****************************************************'
!PRINT *, '******** HARDCODED GRIBEX COMPABILITY MODE *********'
!PRINT *, '****************************************************'
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

! Message passing setup
! Participating processors limited by -P option 

!--------------------------
 ZT=TIMEF()
 CALL MPL_INIT()

 NPROC=MPL_NPROC()
 MYPROC = MPL_MYRANK()
 IPROC_OLD=NPROC
 IF(IPROC_OLD > IPROC) THEN
   CALL MPL_LOCOMM_CREATE(IPROC,ICOMM) 
   IF(MYPROC > IPROC) THEN
     CALL MPL_BARRIER()
     CALL MPL_END()
     STOP
   ENDIF 
   CALL MPL_SETDFLT_COMM(ICOMM,ICOMM_OLD)
   NPROC=IPROC
 ENDIF
!-------------------------

ALLOCATE(NPRCIDS(NPROC))
DO JJ=1,NPROC
  NPRCIDS(JJ) = JJ
ENDDO
ITAG = 191919

IF(MYPROC == 1) THEN
  IF(CINGPF == ' ') THEN
    PRINT *,' INPUT FILE NAME HAS NOT BEEN SUPPLIED'
    PRINT *,' FILE fort.11 WILL BE USED AS INPUT'
    CINGPF = 'fort.11'
  ENDIF
  IF(COUTSF == ' ') THEN
    PRINT *,' OUTPUT SPECTRAL FILE NAME HAS NOT BEEN SUPPLIED'
    PRINT *,' FILE fort.12 WILL BE USED FOR SPECTRAL OUTPUT'
    COUTSF = 'fort.12'
  ENDIF
  IF(COUTGPF == ' ') THEN
    PRINT *,' OUTPUT GRID-POINT FILE NAME HAS NOT BEEN SUPPLIED'
    PRINT *,' FILE fort.10 WILL BE USED FOR GRID-POINT OUTPUT'
    COUTGPF = 'fort.10'
  ENDIF
ENDIF

ICODE = 0

IF(CFIELD /= ' ') THEN
  READ(CFIELD,'(F7.0)') ZCODE

  ! Handle possible param.table notation
  ICODE = FLOOR(ZCODE)
  ITABLE = NINT(1000*(ZCODE-ICODE))
  IF (ITABLE /= 128) ICODE = 1000*ITABLE + ICODE
ENDIF

CALL GRIB_GRIBEX_MODE_ON()

! Find spectral resolution

CALL GRIB_OPEN_FILE(INSF,CINGPF,'R',IRET)
IF(IRET /= GRIB_SUCCESS) THEN
  WRITE(NERR,*) ' ERROR OPENING FILE INPUT GRIDPOINT FILE',CINGPF,IRET
  CALL ABOR1('GPTOSP:ERROR OPENING FILE INPUT GRIDPOINT FILE')
ENDIF
CALL GRIB_NEW_FROM_FILE(INSF,IGRIB(1),IRET)
IF(IRET /= GRIB_SUCCESS) THEN
  WRITE(NERR,*)' ERROR IN FILE ',CINGPF,' : NO INFORMATION'
  CALL ABOR1('GPTOSP:ERROR GRIB_NEW_FROM_FILE')
ENDIF
CALL GRIB_GET(IGRIB(1),'gridType',CGRIDTYPE,IRET)
IF(IRET /= GRIB_SUCCESS) THEN
  WRITE(NERR,*)' ERROR GRIB_GET gridType',IRET
  CALL ABOR1('GPTOSP:ERROR GRIB_GET')
ENDIF
CALL GRIB_GET(IGRIB(1),'localDefinitionNumber',ILOCALDEF,IRET)
IF(IRET /= GRIB_SUCCESS) THEN
  WRITE(NERR,*)' ERROR GRIB_GET localDefinitionNumber',IRET
  CALL ABOR1('GPTOSP:ERROR GRIB_GET')
ENDIF
IF(TRIM(CGRIDTYPE) == 'sh') THEN
  WRITE(NERR,*)' INPUT DATA NOT IN GRIDPOINT FORM'
  CALL ABOR1('GPTOSP:INPUT DATA IN SPECTRAL FORM')
ENDIF

!Decide spectral resolution

CALL GRIB_GET(IGRIB(1),'Nj',NDGL)
ALLOCATE(NLOEN(NDGL))
IF(TRIM(CGRIDTYPE) == 'reduced_gg') THEN
  CALL GRIB_GET(IGRIB(1),'pl',NLOEN)
ELSE
  CALL GRIB_GET(IGRIB(1),'Ni',NLOEN(1))    
  DO JGL=2,NDGL
    NLOEN(JGL) = NLOEN(1)
  ENDDO
ENDIF

CALL GRIB_RELEASE(IGRIB(1))
!CALL GRIB_CLOSE_FILE(INSF)

IF(ITRUNC == 0) THEN
  IF(NLIN == 0) THEN
    NSMAX=(2*NDGL-1)/3
  ELSE
    NSMAX=(2*NDGL-1)/2
  ENDIF
ELSE
  NSMAX=ITRUNC
ENDIF

PRINT *, 'Spectral truncation: ', NSMAX

IF(NSMAX > 511) IMAXFLD=5
IF(NSMAX > 800) IMAXFLD=1

! Prepare for transforms

CALL SETUP_TRANS0(KOUT=NOUT,KERR=0,KPRINTLEV=0,KMAX_RESOL=1,&
&                 KPRGPNS=NPROC,KPRGPEW=1,KPRTRW=NPROC,LDMPOFF=LSCAL)
CALL SETUP_TRANS(KSMAX=NSMAX,KDGL=NDGL,KLOEN=NLOEN,LDSPLIT=.FALSE.,&
&                LDUSEFFTW=.TRUE.)
!
CALL TRANS_INQ(KSPEC2=NSPEC2,KSPEC2G=NSPEC2G,KGPTOT=NGPTOT,KGPTOTG=NGPTOTG)


! Open files

IF(MYPROC == 1) THEN
 
  IF (ILOCALDEF == 14  .OR. ILOCALDEF == 37) THEN   ! Channels are vertical coordinates 
    CALL GRIB_INDEX_CREATE(INSF,CINGPF,'channelNumber,ifsParam',IRET)
    CALL GRIB_INDEX_GET_SIZE(INSF,'channelNumber',INLEVS)
    ALLOCATE(ilevel(INLEVS))
    CALL GRIB_INDEX_GET(INSF,'channelNumber',ILEVEL)
  ELSE
    CALL GRIB_INDEX_CREATE(INSF,CINGPF,'level,ifsParam',IRET)
    CALL GRIB_INDEX_GET_SIZE(INSF,'level',INLEVS)
    ALLOCATE(ilevel(INLEVS))
    CALL GRIB_INDEX_GET(INSF,'level',ILEVEL)
  ENDIF
  CALL GRIB_INDEX_GET_SIZE(INSF,'ifsParam',INPARS)
  ALLOCATE(IFSPARAM(INPARS))
  CALL GRIB_INDEX_GET(INSF,'ifsParam',IFSPARAM)
  IF(IRET /= GRIB_SUCCESS) THEN
    WRITE(NERR,*) ' ERROR OPENING FILE INPUT GRIDPOINT FILE',CINGPF,IRET
    CALL ABOR1(' GPTOSP:ERROR OPENING FILE INPUT GRIDPOINT FILE')
  ENDIF

  CALL GRIB_OPEN_FILE(IOUTSF,COUTSF,'W',IRET)
  IF(IRET /= GRIB_SUCCESS) THEN
    WRITE(NERR,*) ' ERROR OPENING FILE OUTPUT SPECTRAL FILE',COUTSF,IRET
    CALL ABOR1(' GPTOSP:ERROR OPENING OUTPUT SPECTRAL FILE')
  ENDIF
  IF(ICODE /= 0) THEN
  CALL GRIB_OPEN_FILE(IOUTGPF,COUTGPF,'W',IRET)
    IF(IRET /= GRIB_SUCCESS) THEN
      WRITE(NERR,*) ' ERROR OPENING FILE OUTPUT GP. FILE',COUTGPF,IRET
      CALL ABOR1('GPTOSP:ERROR OPENING OUTPUT GP. FILE')
    ENDIF
  ENDIF
ENDIF

IF(NPROC > 1) THEN
  CALL MPL_BROADCAST(INPARS,KROOT=1,KTAG=ITAG, &
   &   CDSTRING='SPTOGP:')
  CALL MPL_BROADCAST(INLEVS,KROOT=1,KTAG=ITAG, &
   &   CDSTRING='SPTOGP:')
ENDIF
IMAXFLD=INPARS
ALLOCATE(ZSPECG(IMAXFLD,NSPEC2G))
ALLOCATE(ZSPEC(IMAXFLD,NSPEC2))
ALLOCATE(ZFPDAT(MAX(NGPTOTG,NSPEC2G)))
ALLOCATE(ZG(NGPTOT,IMAXFLD,1))
ALLOCATE(ZGG(NGPTOTG,IMAXFLD))
ALLOCATE(ITO(IMAXFLD))
IF(LVD2UV) THEN
  ALLOCATE(ZSPVOR(1,NSPEC2))
  ALLOCATE(ZSPDIV(1,NSPEC2))
ENDIF


! Gridpoint to spectral transform

ITO(:) = 1

! Inititialize GRIB_API handles to zero
IGRIB(:) = 0
ISAMPLE = 0
IGRIBOUT = 0
IEDITION = 0
DO JLEV=1,INLEVS
  IFLD = 0
  IF(MYPROC == 1) THEN

    IF (ILOCALDEF == 14  .OR. ILOCALDEF == 37) THEN   ! Channels are vertical coordinates 
      CALL GRIB_INDEX_SELECT(INSF,'channelNumber',ILEVEL(JLEV))
    ELSE
      CALL GRIB_INDEX_SELECT(INSF,'level',ILEVEL(JLEV))
    ENDIF
    DO JPAR=1,INPARS
      CALL GRIB_INDEX_SELECT(INSF,'ifsParam',IFSPARAM(JPAR))
      CALL GRIB_NEW_FROM_INDEX(INSF,IGRIB(IFLD+1), IRET)
      DO WHILE (IRET /= GRIB_END_OF_INDEX )
        IF(IRET /= GRIB_SUCCESS) THEN
          WRITE(NERR,*) ' ERROR GRIB_NEW_FROM_FILE',IRET
          CALL ABOR1('SPTOGP:ERROR GRIB_NEW_FROM_INDEX')
        ENDIF
        IPARAM(IFLD+1) = ifsParam(jpar)
        CALL GRIB_GET(IGRIB(IFLD+1),'edition',IEDITION(IFLD+1))
        IF(IRET /= GRIB_SUCCESS) THEN
          WRITE(NERR,*)' ERROR GRIB_GET edition'
          CALL ABOR1('GPTOSP:ERROR GRIB_GET edition')
        ENDIF

        ! Write out "skipped field" to output gridpoint file
        IF(IPARAM(IFLD+1) /= ICODE.AND.ICODE /= 0 .AND. &
         & .NOT. LLSGINT(IPARAM(IFLD+1),ICODE)) THEN
          WRITE(0,*)' FIELD ',IPARAM(IFLD+1),' NOT TRANSFORMED'
          CALL GRIB_CLONE(IGRIB(IFLD+1),IGRIBOUT,IRET)
          IF(IRET /= GRIB_SUCCESS) THEN
            WRITE(NERR,*)'GPTOSP:ERROR GRIB_CLONE'
            CALL ABOR1('GPTOSP:ERROR GRIB_CLONE')
          ENDIF
          CALL GRIB_WRITE(IGRIBOUT,IOUTGPF,IRET)
          IF(IRET /= GRIB_SUCCESS) THEN
            WRITE(NERR,*)' ERROR 3b'
            CALL ABOR1('GPTOSP:ERROR GRIB_WRITE')
          ENDIF
          CALL GRIB_RELEASE(IGRIBOUT)
          CALL GRIB_RELEASE(IGRIB(IFLD+1))
          IFLD=IFLD-1
        ELSE
          CALL GRIB_GET(IGRIB(IFLD+1),'values',ZFPDAT,IRET)
          IF(IRET /= GRIB_SUCCESS) THEN
            WRITE(NERR,*)' ERROR GRIB_GET values ',IRET
            CALL ABOR1('GPTOSP:ERROR GRIB_GET values')
          ENDIF
          ZGG(:,IFLD+1) = ZFPDAT(:)
        ENDIF
        IFLD=IFLD+1
        CALL GRIB_NEW_FROM_INDEX(INSF,IGRIB(IFLD+1), IRET)
      ENDDO
    ENDDO

  ENDIF
      ! Send number of fields in this batch to other processors

  IF(NPROC > 1) THEN
    CALL MPL_BROADCAST(IFLD,KROOT=1,KTAG=ITAG, &
             &   CDSTRING='SPTOGP:')
    CALL MPL_BROADCAST(IPARAM(1:IFLD),KROOT=1,KTAG=ITAG, &
             &   CDSTRING='SPTOGP:')
  ENDIF
  IF(IFLD == 0 ) CYCLE
  ! Syncronize processors
!!$  IF(NPROC > 1) THEN
!!$    CALL MPL_BARRIER()
!!$  ENDIF
  ! Distribute gridpoint fields to processors
  CALL DIST_GRID(PGPG=ZGG,KFDISTG=IFLD,KFROM=ITO,PGP=ZG)
  ! Spectral transform
  IF(LVD2UV) THEN
    ISF = 0
    IGRIB_SAVE=IGRIB(:)
    ZGG(1:NGPTOT,1:IFLD) = ZG(1:NGPTOT,1:IFLD,1)
    DO JFLD=1,IFLD
      IF(IPARAM(JFLD) == 131) THEN
        ZG(1:NGPTOT,1,1)=ZGG(1:NGPTOT,JFLD)
        IGRIB(1) = IGRIB_SAVE(JFLD)
      ELSEIF(IPARAM(JFLD) == 132) THEN 
        ZG(1:NGPTOT,2,1)=ZGG(1:NGPTOT,JFLD)
        IGRIB(2) = IGRIB_SAVE(JFLD)
      ELSE
        ISF=ISF+1
        ZG(1:NGPTOT,2+ISF,1)=ZGG(1:NGPTOT,JFLD)
        IIPARAM(2+ISF) = IPARAM(JFLD)
        IGRIB(2+ISF) = IGRIB_SAVE(JFLD)
      ENDIF
        ENDDO
    IF(ISF == IFLD-1) THEN
      CALL ABOR1('GPTOSP:U OR V MISSING')
      ENDIF
    IF(ISF == IFLD-2) THEN
      IIPARAM(1) =138
      IIPARAM(2) =155
      CALL DIR_TRANS(PSPVOR=ZSPEC(1:1,:),PSPDIV=ZSPEC(2:2,:),PSPSCALAR=ZSPEC(3:,:),PGP=ZG)
    ELSE
      WRITE(NERR,*) 'NO U/V FOR LEVEL ',ilevel(jlev)
      IIPARAM(1:IFLD) = IPARAM(1:IFLD)
      IGRIB(1:IFLD) = IGRIB_SAVE(1:IFLD)
      CALL DIR_TRANS(PSPSCALAR=ZSPEC(1:IFLD,:),PGP=ZG(:,1:IFLD,:))
    ENDIF
  ELSE
    CALL DIR_TRANS(PSPSCALAR=ZSPEC(1:IFLD,:),PGP=ZG(:,1:IFLD,:))
    IIPARAM(1:IFLD) = IPARAM(1:IFLD)
  ENDIF
  ! Gather spectral fields to processor 1
  CALL GATH_SPEC(PSPECG=ZSPECG,KFGATHG=IFLD,KTO=ITO,PSPEC=ZSPEC)

  IF(MYPROC == 1) THEN

    ! Code and write out spectral fields

      DO JFLD=1,IFLD
        WRITE(CEDITION,'(I1)') IEDITION(JFLD)
      CSAMPLESFILE = 'sh_pl_grib'//CEDITION
      CALL GRIB_NEW_FROM_SAMPLES(ISAMPLE,CSAMPLESFILE,IRET)
      IF(IRET /= GRIB_SUCCESS) THEN
        WRITE(NERR,*)' ERROR GRIB_NEW_FROM_SAMPLES ',CSAMPLESFILE
        CALL ABOR1('GPTOSP:ERROR GRIB_NEW_FROM_SAMPLES')
      ENDIF
      CALL GRIB_SET(ISAMPLE,'J',NSMAX)
      CALL GRIB_SET(ISAMPLE,'K',NSMAX)
      CALL GRIB_SET(ISAMPLE,'M',NSMAX)
    
      IF (NSMAX >= 213) THEN
        ISTRUNC = 20
      ELSE
        ISTRUNC = MIN(10,NSMAX)
      ENDIF
      CALL GRIB_SET(ISAMPLE,'JS',ISTRUNC)
      CALL GRIB_SET(ISAMPLE,'KS',ISTRUNC)
      CALL GRIB_SET(ISAMPLE,'MS',ISTRUNC)

      IF (LGRIBEX) THEN
        CALL GRIB_SET(ISAMPLE,'computeLaplacianOperator', 0)
        CALL GRIB_SET(ISAMPLE,'laplacianOperator',0.5_JPRB)
      ENDIF

      CALL GRIB_UTIL_SECTIONS_COPY(IGRIB(JFLD),ISAMPLE, &
            & GRIB_SECTION_PRODUCT+GRIB_SECTION_LOCAL,IGRIBOUT,IRET)
      IF(IRET /= GRIB_SUCCESS) THEN
        WRITE(NERR,*)' ERROR GRIB_UTIL_SECTIONS_COPY ',IRET
        CALL ABOR1('GPTOSP:ERROR GRIB_UTIL_SECTIIONS_COPY')
      ENDIF

      WRITE(0,*) JLEV,JFLD,' FIELD ',IPARAM(JFLD),' TRANSFORMED'
      IF(FACT /= 1.0_JPRB) THEN
        PRINT *, ' SMOOTHING FACTOR=',FACT,' EXPONENT=',NEXPO
        IEXP=NEXPO/2
        ZFACT=FACT-1.0_JPRB
        ISE=0
        DO JM=0,NSMAX
!	      II=1+MIN(1,IABS(JM))
!	      DO JI=1,II
          DO JN=JM,NSMAX
            ISE=ISE+1
!	        ISE=NASM0(JM)+(JN-JM)*2+JI-1
            ZFAC=1.0_JPRB+ZFACT*(JN*(JN+1.0_JPRB))**IEXP/(NSMAX*(NSMAX+1.0_JPRB))**IEXP
            ZFPDAT(ISE)=ZSPECG(JFLD,ISE)/ZFAC
            ISE=ISE+1
            ZFPDAT(ISE)=ZSPECG(JFLD,ISE)/ZFAC
          ENDDO
!	    ENDDO
        ENDDO
      ELSE
        ZFPDAT(1:NSPEC2G) = ZSPECG(JFLD,:)
      ENDIF

      CALL GRIB_GET(IGRIB(JFLD),'levelType',CLEVELTYPE)
      IF ( CLEVELTYPE(1:2)=='ml' .AND. &
         & (IPARAM(JFLD) == 152 .OR. IPARAM(JFLD) == 129) ) THEN
        CALL GRIB_SET(IGRIBOUT,'computeLaplacianOperator',0)
        CALL GRIB_SET(ISAMPLE,'laplacianOperator',0.5_JPRB)
      ENDIF
      
      CALL GRIB_SET(IGRIBOUT,'ifsParam',iiparam(jfld))
      CALL GRIB_SET(IGRIBOUT,'values',ZFPDAT(1:NSPEC2G),IRET)
      IF(IRET /= GRIB_SUCCESS) THEN
        WRITE(NERR,*)' ERROR GRIB_SET values'
        CALL ABOR1('GPTOSP:ERROR GRIB_SET values')
      ENDIF
      CALL GRIB_WRITE(IGRIBOUT,IOUTSF,IRET)
      IF(IRET /= GRIB_SUCCESS) THEN
        WRITE(NERR,*)' ERROR GRIB_WRITE IOUTSF'
        CALL ABOR1('GPTOSP:ERROR GRIB_WRITE IOUTSF')
      ENDIF
      
      CALL GRIB_RELEASE(ISAMPLE)
      CALL GRIB_RELEASE(IGRIB(JFLD))
      CALL GRIB_RELEASE(IGRIBOUT)
    ENDDO
  ENDIF
  ! Syncronize processors
!!$  IF(NPROC > 1) THEN
!!$    CALL MPL_BARRIER()
!!$  ENDIF
  IFLD = 0
ENDDO
write(0,*) 'closing files'
IF (MYPROC == 1) THEN
!  CALL GRIB_CLOSE_FILE(INSF)
  IF(ICODE /= 0) CALL GRIB_CLOSE_FILE(IOUTGPF)
  CALL GRIB_CLOSE_FILE(IOUTSF)
ENDIF

!           gather stack usage statistics
!!$ISTACK = GETSTACKUSAGE()
!!$IF(MYPROC == 1) THEN
!!$  PRINT 9000, istack
!!$  9000 FORMAT("Stack Utilisation Information",/,&
!!$       &"=============================",//,&
!!$       &"Node           Size(Bytes)",/,&
!!$       &"====           ===========",//,&
!!$       &"   1",11x,I10)
!!$
!!$  DO I=2,NPROC
!!$    CALL MPL_RECV(ISTACK,KSOURCE=NPRCIDS(I),KTAG=I, &
!!$         & CDSTRING='GPTOSP:')
!!$    PRINT '(I4,11X,I10)', I,ISTACK
!!$  ENDDO
!!$ELSE
!!$  CALL MPL_SEND(ISTACK,KDEST=NPRCIDS(1),KTAG=MYPROC, &
!!$             &   CDSTRING='GPTOSP:')
!!$ENDIF

!Close down message passing

!--------------------------
 IF(IPROC_OLD > IPROC) THEN
     MPL_COMM_OML(1)=MPI_COMM_WORLD
     MPL_NUMPROC=IPROC_OLD
     CALL MPL_SETDFLT_COMM(ICOMM_OLD,ICOMM)
 ENDIF

 write(0,*) "Calling barrier"
 CALL MPL_BARRIER()
 CALL MPL_END()
 ZT=(TIMEF()-ZT)/1000.0_JPRB
 IF(MYPROC == 1) write(0,'(a,I3,a,I4,a,F9.2,a)') &
    & "GPTOSP, on",NPROC," out of",IPROC_OLD," procs, took",ZT," sec"
!--------------------------

STOP

CONTAINS  

!     ------------------------------------------------------------------

SUBROUTINE USE_GPTOSP

!   WRITE MESSAGE TO INFORM ABOUT CORRECT USE OF PROGRAM

WRITE(NERR,*) ' CORRECT OPTIONS AND ARGUMENTS FOR GPTOSP ARE :'
WRITE(NERR,*) '   -g    input filename (grid-point) (def: fort.11)'
WRITE(NERR,*) '   -S    output spectral  filename (def: fort.12)'
WRITE(NERR,*) '   -T    spectral truncation of spectral output'
WRITE(NERR,*) '   -G    output grid-point filename (def: fort.10)'
WRITE(NERR,*) '   -l    if linear grid (default quadratic)'
WRITE(NERR,*) '   -f    field code to convert to SP (def: 0)'
WRITE(NERR,*) '         if -f 0, all fields will be converted'
WRITE(NERR,*) '         if -f -1, fields needed for sgint_fast'
WRITE(NERR,*) '   -r    reduction factor for the smoother (def: 1.)'
WRITE(NERR,*) '   -e    exponent for the spectral smoother (def: 4)'
WRITE(NERR,*) '   -X    try make output identical to old GRIBEX'
WRITE(NERR,*) '   -h    displays options and arguments'
WRITE(NERR,*) '   -P    number of processors to use (mandatory for paralle1)'
WRITE(NERR,*) '   -U    Go  u and v in grid-point space to vorticity divergence'

END SUBROUTINE USE_GPTOSP

!     ------------------------------------------------------------------

LOGICAL FUNCTION LLSGINT(KPARAM,KCODE)

INTEGER(KIND=JPIM) :: KCODE,KPARAM
INTEGER(KIND=JPIM) :: INCLUDE(26),JJPAR
 
