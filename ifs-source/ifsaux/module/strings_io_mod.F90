MODULE STRINGS_IO_MOD

!**** Interface to STRINGS_IO

!     Purpose.
!     --------
!     Fortran 90 Interface to calling strings IO 

!     Author.
!     -------
!        P.Gillies                      ECMWF
!          adapted from bytes_io_mod by
!          W.Deconinck and M.Hamrud     ECMWF

!     Modifications.
!     --------------
!        Original: 2022-11-17

!     ------------------------------------------------------------------

USE PARKIND1 , ONLY : JPRD, JPIM, JPRM, JPRB
USE YOMHOOK  , ONLY : LHOOK, DR_HOOK, JPHOOK
USE MPL_MODULE, ONLY : MPL_ABORT

IMPLICIT NONE

PRIVATE :: JPRD, JPIM, JPRM
PRIVATE :: LHOOK, DR_HOOK, JPHOOK

PRIVATE

PUBLIC :: STRINGS_IO_OPEN
PUBLIC :: STRINGS_IO_CLOSE
PUBLIC :: STRINGS_IO_WRITE
PUBLIC :: STRINGS_IO_READ

INTEGER, PARAMETER, PUBLIC :: JPSTRINGS_IO_SUCCESS=0
INTEGER, PARAMETER :: JPSTRINGS_IO_COULD_NOT_OPEN_FILE=-1
INTEGER, PARAMETER :: JPSTRINGS_IO_COULD_NOT_CLOSE_FILE=-1
INTEGER, PARAMETER :: JPSTRINGS_IO_INVALID_FILE_NAME=-2
INTEGER, PARAMETER :: JPSTRINGS_IO_INVALID_OPEN_MODE=-3
INTEGER, PARAMETER :: JPSTRINGS_IO_END_OF_FILE=-1
INTEGER, PARAMETER :: JPSTRINGS_IO_READ_JPIM_ERROR=-2
INTEGER, PARAMETER :: JPSTRINGS_IO_WRITE_JPIM_ERROR=-1

CONTAINS


SUBROUTINE STRINGS_IO_OPEN(KFILE,CDPATH,CDMODE,KRET)
  INTEGER(KIND=JPIM),INTENT(OUT)  :: KFILE
  CHARACTER(LEN=*)  ,INTENT(IN)   :: CDPATH
  CHARACTER(LEN=1)  ,INTENT(IN)   :: CDMODE
  INTEGER(KIND=JPIM),OPTIONAL,INTENT(OUT) :: KRET
  INTEGER(KIND=JPIM) :: IRET
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('STRINGS_IO:STRINGS_IO_OPEN',0,ZHOOK_HANDLE)
  CALL C_STRINGS_IO_OPEN(KFILE,CDPATH,CDMODE,IRET)
  IF(PRESENT(KRET)) THEN
    KRET = IRET
  ELSEIF (IRET < JPSTRINGS_IO_SUCCESS) THEN
    WRITE(0,*) 'STRINGS_IO ',TRIM(CDPATH),' FAILED',IRET
  ENDIF
  IF (LHOOK) CALL DR_HOOK('STRINGS_IO:STRINGS_IO_OPEN',1,ZHOOK_HANDLE)
END SUBROUTINE STRINGS_IO_OPEN

SUBROUTINE STRINGS_IO_CLOSE(KFILE,KRET)
  INTEGER(KIND=JPIM),INTENT(IN)  :: KFILE
  INTEGER(KIND=JPIM),OPTIONAL,INTENT(OUT) :: KRET
  INTEGER(KIND=JPIM) :: IRET
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('STRINGS_IO:STRINGS_IO_CLOSE',0,ZHOOK_HANDLE)
  CALL C_STRINGS_IO_CLOSE(KFILE,IRET)
  IF(PRESENT(KRET)) THEN
    KRET = IRET
  ELSEIF (IRET < JPSTRINGS_IO_SUCCESS) THEN
    WRITE(0,*) 'STRINGS_IO_CLOSE ',KFILE,' FAILED',IRET
    CALL MPL_ABORT('STRINGSS_IO_CLOSE FAILED')
  ENDIF
  IF (LHOOK) CALL DR_HOOK('STRINGS_IO:STRINGS_IO_CLOSE',1,ZHOOK_HANDLE)
END SUBROUTINE STRINGS_IO_CLOSE

SUBROUTINE STRINGS_IO_READ(KFILE,CDBUF,KCHARS,KRET)
  INTEGER(KIND=JPIM),INTENT(IN)    :: KFILE
  CHARACTER(LEN=*)  ,INTENT(OUT)   :: CDBUF
  INTEGER(KIND=JPIM),INTENT(INOUT) :: KCHARS
  INTEGER(KIND=JPIM),INTENT(OUT), OPTIONAL   :: KRET
  INTEGER(KIND=JPIM) :: IRET,ILEN
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('STRINGS_IO:STRINGS_IO_READ_JPIM_CHAR_ARRAY',0,ZHOOK_HANDLE)
  CALL C_STRINGS_IO_READ(KFILE,CDBUF,KCHARS,IRET)
  IF(PRESENT(KRET)) THEN
    KRET=IRET
  ELSEIF(IRET < JPSTRINGS_IO_SUCCESS .AND. IRET < JPSTRINGS_IO_END_OF_FILE ) THEN
    WRITE(0,*) 'STRINGS_IO_READ_JPIM_CHAR_ARRAY ',KFILE,' FAILED',IRET
    CALL MPL_ABORT('STRINGS_IO_READ_JPIM_CHAR_ARRAY FAILED')
  ENDIF
  IF (LHOOK) CALL DR_HOOK('STRINGS_IO:STRINGS_IO_READ_JPIM_CHAR_ARRAY',1,ZHOOK_HANDLE)
END SUBROUTINE STRINGS_IO_READ

SUBROUTINE STRINGS_IO_WRITE(KFILE,CDBUF,KCHARS,KRET)
  INTEGER(KIND=JPIM),INTENT(IN)            :: KFILE
  CHARACTER(LEN=*)  ,INTENT(IN)            :: CDBUF
  INTEGER(KIND=JPIM),INTENT(IN),  OPTIONAL :: KCHARS
  INTEGER(KIND=JPIM),INTENT(OUT), OPTIONAL :: KRET
  INTEGER(KIND=JPIM) :: ICHARS
  INTEGER(KIND=JPIM) :: IRET
  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE
  IF (LHOOK) CALL DR_HOOK('STRINGS_IO:STRINGS_IO_WRITE_CHAR_ARRAY',0,ZHOOK_HANDLE)
  IF(PRESENT(KCHARS)) THEN
    ICHARS=KCHARS
  ELSE
    ICHARS=LEN_TRIM(CDBUF)
  ENDIF
  CALL C_STRINGS_IO_WRITE(KFILE,CDBUF,INT(ICHARS,JPIM),IRET)
  IF(PRESENT(KRET)) THEN
    KRET=IRET
  ELSEIF(IRET < JPSTRINGS_IO_SUCCESS) THEN
    WRITE(0,*) 'STRINGS_IO_WRITE_CHAR_ARRAY ',KFILE,' FAILED',IRET
    CALL MPL_ABORT('STRINGS_IO_WRITE_CHAR_ARRAY FAILED')
  ENDIF
  IF (LHOOK) CALL DR_HOOK('STRINGS_IO:STRINGS_IO_WRITE_CHAR_ARRAY',1,ZHOOK_HANDLE)
END SUBROUTINE STRINGS_IO_WRITE

END MODULE
